// Версия приходит из klient.pro голым числом (JF_VERSION_RAW), а в
// строку превращается здесь. Так сделано потому, что кавычки в
// DEFINES не переживают препроцессор симбиановского инструментария.
//
// Подстраховка на случай сборки в обход .pro -- лучше «?» в журнале,
// чем отказ компиляции.
#define JF_STR2(x) #x
#define JF_STR(x) JF_STR2(x)
#ifdef JF_VERSION_RAW
#define JF_VERSION JF_STR(JF_VERSION_RAW)
#else
#define JF_VERSION "?"
#endif

