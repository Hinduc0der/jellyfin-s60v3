//
// Язык выбирается ПРИ СБОРКЕ: `qmake DEFINES+=JF_EN` даёт английское
// приложение, без этого -- русское. Внутри пакета при этом не меняется
// ничего, кроме текстов: тот же UID3, та же версия, то же имя. Значит
// английская сборка ставится поверх русской как обновление, а рядом с ней
// не встанет -- чего мы и хотели.
//
// Почему не QTranslator и .ts-файлы, как принято в Qt. Перевод на ходу
// требует везти в пакете .qm-файл и держать переключатель языка в
// настройках. На кнопочном телефоне язык выбирают один раз и больше к
// этому не возвращаются, а каждый лишний файл в пакете -- лишний способ
// сломать установку. Две сборки обходятся одной строкой в команде.
//
// В журнал пишутся те же строки, что на экран. При разборе чужой беды
// присланный журнал должен читаться тем, кто его присылает: иначе человек
// не понимает, что посылает, и не посылает вовсе.

