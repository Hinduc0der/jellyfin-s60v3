# Экран телефона по умолчанию -- если приложение своего не назвало.
#
# Правильнее, когда размер называет само приложение: один компаньон обслужит
# и E90 с его 800x352, и обычный S60 с 240x320, и ничего настраивать руками
# не придётся. Эта переменная -- только запасной вариант для плеера, который
# пришёл по голому адресу, без участия приложения.
def razbor_ekrana(text, default=(800, 352)):
    """Разобрать запись вида 320x240. Непонятное -- молча в умолчание."""
    spotted = re.match(r"^(\d{2,4})x(\d{2,4})$", (text or "").strip(),
                       flags=re.IGNORECASE)
    if not spotted:
        return default
    width, height = int(spotted.group(1)), int(spotted.group(2))
    # Пределы здравого смысла: меньше -- не видно, больше -- не покажет ни
    # один телефон тех лет, а работы кодировщику прибавится вдвое.
    if not (80 <= width <= 1280 and 60 <= height <= 720):
        return default
    # Чётные стороны: кодировщик иначе округлит сам, и объявленный в описании
    # размер разойдётся с настоящим.
    return (width - width % 2, height - height % 2)


