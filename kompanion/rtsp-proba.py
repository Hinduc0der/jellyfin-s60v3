def note(text):
    try:
        with io.open(LOG, "a", encoding="utf-8") as handle:
            handle.write(text + "\n")
    except Exception:
        pass
    if sys.stdout is not None:
        try:
            print(text)
        except Exception:
            pass


def jellyfin_token():
    """Токен Jellyfin из файла рядом. В журнал он не попадает никогда."""
    try:
        with io.open(TOKEN_FILE, encoding="utf-8") as handle:
            for line in handle:
                if line.strip().upper().startswith("TOKEN="):
                    return line.split("=", 1)[1].strip()
    except Exception as error:
        note("токен Jellyfin не прочитан: %s" % error)
    return ""


def source_of(name, filename):
    """Откуда брать поток: файл рядом или запись прямо из Jellyfin."""
    item = TWEAKS.get(name, {}).get("jellyfin")
    if item:
        return "%s/Videos/%s/stream?static=true&api_key=%s" % (
            JELLYFIN, item, jellyfin_token())
    return os.path.join(HERE, filename)


def hide_token(text):
    """Убрать токен из строки перед записью в журнал."""
    if "api_key=" in text:
        head, _, tail = text.partition("api_key=")
        rest = tail.split(" ", 1)
        text = head + "api_key=<скрыт>" + (" " + rest[1] if len(rest) > 1 else "")
    return text


def describe_file(path):
    """Длительность, размер кадра и ЧАСТОТА КАДРОВ источника.

    Частота нужна, чтобы не назначать её своей рукой. На живой пробе я задал
    25 кадров «как в источнике», а там было 24 -- ffmpeg дописал 155
    дублированных кадров за 155 секунд, по одному в секунду. Снаружи это
    выглядит как лёгкая запинка раз в секунду, и владелец принял её за стиль
    мультика. Правильно -- брать частоту из источника.
    """
    # Жалобы ffprobe НЕ выбрасываем. Раньше здесь стоял DEVNULL, и запись,
    # которую ffprobe не осилил, превращалась в одну строку «не опознана --
    # нет длительности»: ни кода ошибки, ни причины. На телефоне это
    # «воспроизведение клипа невозможно», и дальше гадай.
    #
    # Тайм-аут нужен по той же причине: источник -- не файл на диске, а поток
    # от Jellyfin по сети. Если он не отвечает, ffprobe ждёт вечно, а вместе
    # с ним и весь разбор запроса.
    try:
        probe = subprocess.run(
            [FFPROBE, "-v", "error", "-show_entries",
             "format=duration:stream=width,height,r_frame_rate",
             "-of", "default=nw=1", path],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
    except subprocess.TimeoutExpired:
        note("ffprobe молчит больше минуты: %s" % hide_token(path))
        return 0.0, None, None, None

    out = probe.stdout.decode("ascii", "replace")
    beda = probe.stderr.decode("utf-8", "replace").strip()
    if beda:
        # Текст ffprobe бывает в несколько строк; в журнал кладём одной.
        note("ffprobe жалуется: %s" % " | ".join(beda.splitlines()))
    found = {}
    for line in out.splitlines():
        key, _, value = line.partition("=")
        if key and key not in found and value not in ("", "N/A"):
            found[key] = value
    try:
        duration = float(found.get("duration", 0))
    except ValueError:
        duration = 0.0

    fps = None
    rate = found.get("r_frame_rate", "")
    if "/" in rate:
        top, _, bottom = rate.partition("/")
        try:
            if float(bottom):
                fps = float(top) / float(bottom)
        except ValueError:
            fps = None

    return duration, found.get("width"), found.get("height"), fps


def tune_fmtp(line):
    """Подогнать строки fmtp под то, что пишут чужие серверы.

    Два отличия, замеренных сличением с VLC на том же файле:

      * видео: ffmpeg объявляет `profile-level-id=1`, VLC -- `3`. Уровень 1
        у MPEG-4 Simple Profile это 176x144 и 64 кбит/с, то есть ровно наш
        предел без запаса. Строгий декодер смотрит на объявленный уровень и
        отказывается, если поток хоть чуть его превышает. Уровень 3 даёт запас
        и при этом остаётся Simple Profile.
      * звук: VLC добавляет `streamtype=5` и `Profile=1`, которых ffmpeg не
        пишет. Часть клиентов без них не узнаёт поток.
    """
    if line.startswith("a=fmtp:") and "profile-level-id=1;" in line and "config=0000" in line:
        line = line.replace("profile-level-id=1;", "profile-level-id=3;", 1)

    if line.startswith("a=fmtp:") and "mode=AAC-hbr" in line and "streamtype=" not in line:
        line = line + "; streamtype=5; Profile=1"

    return line


def add_3gpp(section, size):
    """Дописать в дорожку строки, которых ждёт клиент 3GPP PSS.

    Клиент внутри RealPlayer на Nokia -- Helix DNA, то есть клиент стандарта
    3GPP PSS. Он рассчитывает буфер по этим строкам, а ffmpeg их не пишет вовсе:

      b=RR -- сколько отводится на отчёты о приёме. Для серверов Darwin
        известна беда именно с телефонами Nokia: при нуле поток не идёт, и в
        живых инструкциях эту строку правили на 800.
      a=X-predecbufsize -- размер буфера до декодера, в байтах.
      a=X-initpredecbufperiod -- сколько набрать до начала.
      a=framesize -- размер кадра отдельной строкой.

    Числа взяты с запасом на две секунды: для такого битрейта это заведомо
    посильно телефону и совпадает с тем запасом, который мы и так даём подачей.

    ## Про единицу запаса: проверено опытом, трогать не надо

    Одно время здесь стояла поправка. Рассуждение было такое: единица этого
    поля -- тики часов САМОЙ дорожки, а они разные (90000 у видео, 44100 у
    звука), значит одно число 180000 просит у видео две секунды, а у звука
    четыре -- и звук обязан вступать на 2.08 с позже. Арифметика красиво
    совпадала с жалобой «звук отстаёт на две-три секунды».

    Опыт это опроверг. Сериал с пуска с нуля шёл В ЛАД -- при том самом
    числе 180000 в обеих дорожках -- и разъехался только после паузы на
    29-й секунде. Будь разница в предбуфере настоящей, отставание было бы
    слышно на первой же реплике, до всякой паузы.

    Значит плеер применяет этот запас не так, и одинаковое число в обеих
    дорожках даёт одинаковый запас. Поправку сняли: она ничего не лечила, а
    заставила бы звук вступать на секунду РАНЬШЕ.

    Жалобы на две-три секунды относились к просмотрам, где паузы уже были
    (владелец меняет громкость), то есть к перезапускам -- см. `new_run` и
    `delivered`.
    """
    speed = 64
    for line in section:
        if line.startswith("b=AS:"):
            try:
                speed = int(line[5:])
            except ValueError:
                pass

    section = list(section)
    section.append("b=RR:800")
    section.append("a=X-predecbufsize:%d" % (speed * 250))
    section.append("a=X-initpredecbufperiod:180000")
    if section[0].startswith("m=video") and size[0] and size[1]:
        section.append("a=framesize:96 %s-%s" % (size[0], size[1]))
    return section



def build_sdp(name, filename, streams):
    """Спросить у ffmpeg описание потока для файла и доделать его под RTSP.

    ffmpeg выдаёт описание для "слепой" отправки: с конкретными портами и без
    строк a=control. Для RTSP нужны как раз порты 0 (настоящие назовёт SETUP)
    и названия дорожек, чтобы плеер знал, что именно настраивать.
    """
    source = source_of(name, filename)
    live = TWEAKS.get(name, {}).get("jellyfin")
    if not live and not os.path.isfile(source):
        note("вариант %s пропущен: нет файла %s" % (name, filename))
        return None

    ready = TWEAKS.get(name, {}).get("sdp")
    if ready:
        head = ["v=0", "o=- 0 0 IN IP4 {server}", "s=Proba",
                "c=IN IP4 {client}", "t=0 0", "a=tool:jf-proba"]
        # Реестр дорожек нужен и здесь: без него SETUP не найдёт дорожку и
        # ответит отказом 459.
        CONTROLS[name] = [(line[len("a=control:"):], "video")
                          for line in ready if line.startswith("a=control:")]
        return CRLF.join(head + ready) + CRLF

    # Имя запомненного описания включает отпечаток настроек.
    #
    # Описание несёт в себе строку config= -- заголовок MPEG-4, которым
    # плеер настраивает декодер. Он зависит от того, КАК собран поток:
    # размер кадра, частота, соотношение сторон пикселя. Пока имя файла
    # зависело только от варианта, правка фильтра не доходила до дела:
    # код новый, а описание берётся старое, собранное прежними настройками,
    # и плеер получает заголовок, не совпадающий с потоком.
    #
    # С отпечатком в имени старое описание просто перестаёт находиться и
    # собирается заново. Прежние файлы можно удалить руками, они больше ни
    # на что не влияют.
    otpechatok = hashlib.md5(
        repr(sorted(TWEAKS.get(name, {}).items(), key=str)).encode("utf-8")
    ).hexdigest()[:8]
    scratch = os.path.join(HERE, "sdp-%s-%s.txt" % (name, otpechatok))

    # Для живых вариантов описание собирается долго: ffmpeg открывает запись
    # на Jellyfin, разбирает её и перекодирует кусочек. Поэтому один раз
    # собранное описание запоминается на диске и дальше берётся готовым.
    if live and os.path.isfile(scratch):
        note("вариант %s: описание взято из запомненного" % name)
    elif os.path.exists(scratch):
        os.remove(scratch)

    flags = TWEAKS.get(name, {}).get("rtpflags")
    extra = ["-rtpflags", flags] if flags else []

    plan = TWEAKS.get(name, {}).get("video_plan")
    if plan:
        # Третье число, если оно есть, -- потолок частоты кадров. Разбор
        # обязан совпадать с тем, что делает start(): описание потока и сам
        # поток должны быть собраны ОДНИМИ настройками, иначе плеер получит
        # описание от одной картинки, а пакеты от другой.
        speed, scale = plan[0], plan[1]
        ceiling = plan[2] if len(plan) > 2 else 25.0
        video_opts = target_video(fps_for(source, ceiling), speed, scale)
    else:
        video_opts = TWEAKS.get(name, {}).get("video_opts") or ["-c:v", "copy"]
    audio_opts = TWEAKS.get(name, {}).get("audio_opts") or ["-c:a", "copy"]

    # Берётся ПЕРВАЯ дорожка каждого вида (0:v:0, 0:a:0), а не все сразу.
    # В настоящих записях звуковых дорожек обычно несколько (языки), и ffmpeg
    # на попытку сложить их в один поток RTP отвечает «Only one stream
    # supported in the RTP muxer» -- описание тогда не собирается вовсе.
    command = [FFMPEG, "-hide_banner", "-loglevel", "error", "-i", source]
    if "v" in streams:
        command += ["-map", "0:v:0"] + video_opts + ["-payload_type", "96"]
        command += extra + ["-f", "rtp", "rtp://127.0.0.1:%d" % VIDEO_FROM]
    if "a" in streams:
        command += ["-map", "0:a:0"] + audio_opts + ["-payload_type", "97"]
        limit = TWEAKS.get(name, {}).get("audio_pkt")
        if limit:
            command += ["-pkt_size", str(limit)]
        command += extra + ["-f", "rtp", "rtp://127.0.0.1:%d" % AUDIO_FROM]
    if not (live and os.path.isfile(scratch)):
        # Образец нужен при ЛЮБОМ перекодировании -- и когда настройки заданы
        # списком (video_opts), и когда планом (video_plan). Сначала здесь
        # стоял только список, и у вариантов с планом -- auto в том числе --
        # строки config= в описании не было вовсе. RealPlayer это терпит: он
        # берёт заголовок MPEG-4 из самого потока. Другие клиенты не обязаны.
        if TWEAKS.get(name, {}).get("video_opts") or plan:
            # При перекодировании описание снимается не с источника, а с
            # КОРОТКОГО ОБРАЗЦА, закодированного теми же настройками.
            #
            # Иначе в описании не оказывается строки config= -- заголовка
            # MPEG-4, которым инициализируется декодер: ffmpeg пишет описание
            # раньше, чем кодировщик этот заголовок выдаст. Телефон на такое
            # описание отвечает «не удалось воспроизвести, давайте частично» и
            # играет только звук -- видео завести нечем.
            #
            # Настройки образца те же, что у настоящего потока, поэтому
            # заголовок получается тот самый.
            sample = os.path.join(HERE, "obrazec-%s.mp4" % name)
            making = ([FFMPEG, "-hide_banner", "-loglevel", "error",
                       "-i", source, "-t", "3", "-map", "0:v:0"] + video_opts
                      + ["-map", "0:a:0"] + audio_opts + ["-y", sample])
            note("вариант %s: кодирую образец для описания" % name)
            subprocess.call(making, stdout=subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL)
            if not os.path.isfile(sample):
                note("вариант %s: образец не закодировался" % name)
                return None

            command = [FFMPEG, "-hide_banner", "-loglevel", "error",
                       "-i", sample,
                       "-map", "0:v:0", "-c:v", "copy", "-payload_type", "96"]
            command += extra + ["-f", "rtp", "rtp://127.0.0.1:%d" % VIDEO_FROM]
            command += ["-map", "0:a:0", "-c:a", "copy", "-payload_type", "97"]
            limit = TWEAKS.get(name, {}).get("audio_pkt")
            if limit:
                command += ["-pkt_size", str(limit)]
            command += extra + ["-f", "rtp", "rtp://127.0.0.1:%d" % AUDIO_FROM]

        command += ["-sdp_file", scratch, "-t", "0.1", "-y"]
        subprocess.call(command, stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL)

    if not os.path.isfile(scratch):
        note("вариант %s пропущен: ffmpeg не дал описания" % name)
        return None

    with io.open(scratch, encoding="ascii", errors="replace") as handle:
        given = [line.strip() for line in handle if line.strip()]

    # Своя шапка: адреса сервера и получателя подставляются при DESCRIBE.
    head = ["v=0", "o=- 0 0 IN IP4 {server}", "s=Proba",
            "c=IN IP4 {client}", "t=0 0", "a=tool:jf-proba"]

    # Описание разбирается на дорожки, чтобы в каждую можно было дописать своё.
    sections = []
    for line in given:
        if line.startswith("m="):
            # Порт в описании -- всегда 0: настоящий назовёт SETUP.
            sections.append([re.sub(PORT_IN_M, lambda found: "m=%s 0" % found.group(1), line)])
        elif line.startswith("c="):
            # Адрес получателя уже есть в шапке, в дорожках он лишний.
            continue
        elif sections:
            sections[-1].append(line)

    if not sections:
        note("вариант %s пропущен: в описании нет дорожек" % name)
        return None

    # Объявленная скорость потока. При перекодировании её нельзя брать из
    # описания, которое дал ffmpeg: оно снято с трёхсекундного образца и
    # показывает что попало (92 кбит/с вместо 450). А от неё считается размер
    # буфера, который клиент себе отведёт. Поэтому берётся из заданных
    # настроек -- то есть из того, что мы и правда собираемся отдавать.
    def declared(options, key):
        if key in options:
            value = options[options.index(key) + 1]
            if value.endswith("k"):
                return int(value[:-1])
        return None

    want_video = declared(video_opts, "-b:v")
    want_audio = declared(audio_opts, "-b:a")

    if want_video or want_audio:
        for section in sections:
            speed = want_video if section[0].startswith("m=video") else want_audio
            if not speed:
                continue
            for i, line in enumerate(section):
                if line.startswith("b=AS:"):
                    section[i] = "b=AS:%d" % speed
                    break
            else:
                section.insert(1, "b=AS:%d" % speed)

    pss = TWEAKS.get(name, {}).get("pss")
    # Длительность нужна ВСЕГДА, а не только для вариантов со строками 3GPP:
    # по ней плеер рисует шкалу и разрешает перемотку.
    duration, width, height, _fps = describe_file(source)

    # При перекодировании размер кадра берётся из НАСТРОЕК ВЫХОДА, а не из
    # источника: иначе в описании оказывался размер исходника (1920x1080
    # вместо отдаваемых 800x352), и плеер готовился совсем не к той картинке.
    scaled = re.search(r"scale=(\d+):(\d+)", " ".join(video_opts))
    if scaled:
        width, height = scaled.group(1), scaled.group(2)

    if duration:
        LENGTHS[name] = duration

    if pss and duration:
        # Длительность: без неё клиент не знает, конечный это поток или живой,
        # и не может рассчитать ни буфер, ни перемотку.
        head.append("a=range:npt=0-%.3f" % duration)

    # Имена дорожек. Чужие обкатанные серверы (VLC, Darwin) дают АБСОЛЮТНЫЕ
    # адреса вида .../trackID=0 и отдельно адрес всей сессии. Nokia тех лет
    # работала именно с Darwin, поэтому его манера -- безопасный образец.
    like_others = TWEAKS.get(name, {}).get("like_others")
    if like_others:
        # Имя варианта подставляется при выдаче описания, а не вписывается
        # здесь. Благодаря этому одно и то же описание годится для ЛЮБОЙ
        # записи: собрали раз на частоту кадров -- и дальше только меняем
        # длительность. Иначе на каждую серию приходилось бы кодировать
        # трёхсекундный образец, а это десятки секунд ожидания у телефона.
        head.append("a=control:rtsp://{server}/{variant}")

    body = []
    marks = []
    for number, section in enumerate(sections, start=1):
        if pss:
            section = add_3gpp(section, (width, height))
        if like_others:
            section = [tune_fmtp(line) for line in section]
            suffix = "trackID=%d" % (number - 1)
            section.append("a=control:rtsp://{server}/{variant}/" + suffix)
        else:
            suffix = "track%d" % number
            section.append("a=control:" + suffix)
        marks.append((suffix, "audio" if section[0].startswith("m=audio")
                      else "video"))
        body += section

    CONTROLS[name] = marks
    return "\r\n".join(head + body) + "\r\n"


# Описания-шаблоны по частоте кадров: "shablon-24" и подобные. Строятся один
# раз за всё время работы.
#
# Почему шаблон вообще возможен. В описании потока от содержимого записи
# зависит ровно одна строка -- длительность (`a=range`). Строка `config=`,
# которой инициализируется декодер MPEG-4, зависит только от размера картинки
# и частоты кадров, а они у нас всегда целевые. Проверено сравнением: у
# вариантов с одними настройками config совпадает побайтно, а у варианта с
# 12 кадрами отличается.
#
# Это и делает продукт возможным. Иначе на каждую серию пришлось бы кодировать
# трёхсекундный образец -- десятки секунд, пока телефон ждёт ответа на
# DESCRIBE, и неизвестно, дождётся ли.
TEMPLATE_FPS = {}


# Токены, которые уже проверяли: ключ -> (когда, годен ли). Без памяти
# каждый DESCRIBE бил бы по Jellyfin, а их на одну серию несколько.
KEYS_SEEN = {}
KEY_TTL = 300.0


def key_valid(key):
    """Годен ли токен Jellyfin. Спрашиваем у самого Jellyfin.

    Своего списка паролей заводить не надо и не нужно: у приложения уже есть
    токен, выданный Jellyfin при входе по коду. Кто его предъявил -- тот уже
    вошёл, и проверить это можно одним запросом к Jellyfin.

    Зачем вообще. Без проверки перекодировку запускает кто угодно, кто знает
    вид адреса: на каждый запрос поднимается ffmpeg, и десяток запросов с
    улицы кладёт машину. Это главный предохранитель, и он должен стоять
    ДО запуска ffmpeg, а не после.
    """
    if not key or not re.match(r"^[0-9a-f]{16,64}$", key, flags=re.IGNORECASE):
        return False

    now = time.time()
    seen = KEYS_SEEN.get(key)
    if seen and now - seen[0] < KEY_TTL:
        return seen[1]

    try:
        address = "%s/Users/Me?api_key=%s" % (JELLYFIN, key)
        with urllib.request.urlopen(address, timeout=8) as answer:
            good = answer.status == 200
    except Exception as error:
        # Jellyfin недоступен -- не пускаем. Иначе его падение превращалось бы
        # в открытую дверь, а это худший из возможных исходов.
        note("токен не проверен (%s) -- отказываю" % error)
        good = False

    KEYS_SEEN[key] = (now, good)
    return good


