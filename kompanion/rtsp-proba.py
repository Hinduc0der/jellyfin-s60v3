def speed_for(width, height):
    """Сколько давать на картинку такого размера.

    Считается от проверенного на E90: 600 кбит/с на 800x352. Для экрана
    240x320 это втрое больше точек, чем нужно, и лишние килобиты оплачиваются
    потерями на мобильном канале, а не чёткостью.

    Нижняя граница -- 200: ниже MPEG-4 начинает сыпаться квадратами даже на
    маленькой картинке.
    """
    doly = (width * height) / float(800 * 352)
    return max(200, min(600, int(round(600 * doly / 10.0) * 10)))
