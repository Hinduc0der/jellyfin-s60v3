def fps_for(source, limit=25.0):
    """Какую частоту кадров брать: ту, что в источнике, но не выше предела.

    Назначать её своей рукой нельзя: при несовпадении ffmpeg либо дублирует
    кадры (из 24 в 25 -- один лишний в секунду, видно как запинка), либо
    выбрасывает их неравномерно (из 24 в 15).
    """
    _, _, _, found = describe_file(source)
    if not found or found <= 0:
        note("частота кадров источника не определилась, беру 15")
        return 15
    chosen = min(found, limit)
    # Целое число: дробная частота в RTP и в описании только путает.
    return max(5, int(round(chosen)))


