# подсети. Нужна ровно до тех пор, пока на телефоне стоит сборка, которая
# токена в адрес не кладёт. Когда разойдётся 0.1.4 -- выключить, запустив с
# PROBA_STROGO=1, и тогда токен обязателен для всех.
STROGO = (os.environ.get("PROBA_STROGO") or "0") == "1"


# Короче этого просмотр не считается просмотром, в секундах записи.
#
# Нужно против промаха по кнопке. Jellyfin отметку, присланную явно,
# принимает какой угодно, в том числе уводящую просмотр назад, и своей
# защиты не даёт. Значит отбирать должны мы.
#
# Отбирать можно по одному признаку: сколько записи отдано ЗА ЭТОТ запуск.
# Ткнул не ту серию, увидел не то, вышел -- это несколько секунд.
#
# Чего этот порог НЕ лечит, чтобы потом не искать в нём лишнего. Если
# человек взял ту же запись и нарочно выбрал «с начала», отметка честно
# поедет к началу: это его выбор, и так ведёт себя любой клиент Jellyfin.
# Отличить такое от промаха нечем -- приходит ровно тот же запрос.
MINIMUM = 20.0


def jf_doklad(kuda, item_id, seconds, extra=None, kto=""):
    """Отправить Jellyfin доклад о просмотре. Возвращает код ответа.

    Зачем это здесь, а не в приложении. Место знает только тот, кто отдаёт
    поток: RealPlayer о своих паузах никому не докладывает, и приложение на
    телефоне про них не узнаёт вовсе -- оно всего лишь отдало плееру адрес и
    ушло. А мы видим и PAUSE, и TEARDOWN, и знаем, сколько секунд записи
    отдали. В приложении отметка места и лежала -- мёртвым кодом, который
    ничто не звало; теперь её там нет совсем.

    Без этого «продолжить просмотр» в приложении показывает не то, что
    человек смотрел на самом деле, а отметки, оставленные другими клиентами.
    """
    # Докладываем от имени ЗРИТЕЛЯ, а не от имени служебного пользователя
    # из token.txt. Отметка места -- вещь личная: Jellyfin хранит её в
    # карточке того пользователя, чьим токеном пришёл доклад. Служебный
    # токен остаётся запасным путём -- для старых сборок приложения,
    # которые токена в адрес не кладут и ходят по домашней поблажке.
    token = (kto or "").strip() or jellyfin_token()
    if not token:
        return None
    # Единица времени у Jellyfin -- сто наносекунд.
    telo = {"ItemId": item_id,
            "MediaSourceId": item_id,
            "PositionTicks": int(max(0.0, seconds) * 10000000)}
    if extra:
        telo.update(extra)
    zapros = urllib.request.Request(
        "%s/Sessions/Playing%s" % (JELLYFIN, kuda),
        data=json.dumps(telo).encode("utf-8"), method="POST")
    zapros.add_header("Content-Type", "application/json")
    zapros.add_header("X-Emby-Token", token)
    try:
        with urllib.request.urlopen(zapros, timeout=8) as answer:
            return answer.status
    except Exception as error:
        # Не беда: отметка -- удобство, а не работа. Молчать всё же нельзя,
        # иначе потом не понять, почему отметки не появляются.
        note("Jellyfin не принял доклад%s: %s" % (kuda or " о начале", error))
        return None


def chey(kto):
    """Чьим токеном ушёл доклад -- одним словом, для журнала.

    Сам токен в журнал не попадает никогда. Нужно затем, что отметка места
    ложится в карточку ТОГО пользователя, чьим токеном пришёл доклад, и
    «отметил 300 с (ответ 204)» без этого слова не отличает «записалось
    зрителю» от «записалось служебному пользователю, и зритель этого не
    увидит».
    """
    return "токен зрителя" if (kto or "").strip() else "служебный токен"


def skazat_nachalo(item_id, seconds, kto=""):
    """Просмотр начался.

    Без этого доклада Jellyfin не знает, что просмотр вообще есть: телефона
    нет ни в списке устройств, ни в «Активности», и единственный след --
    отметка места, которая появится уже после. Отсюда и ощущение, что
    приложение серверу ничего не отдаёт.
    """
    if not item_id:
        return
    code = jf_doklad("", item_id, seconds,
                     {"CanSeek": True, "IsPaused": False,
                      "PlayMethod": "Transcode"}, kto)
    if code:
        note("Jellyfin: начал смотреть %s с %.0f с (ответ %d, %s)"
             % (item_id[:8], seconds, code, chey(kto)))


def skazat_hod(item_id, seconds, kto=""):
    """Просмотр идёт -- каждый осмотр, пока поток живой.

    Нужно против потери места при обрыве. Отметка ставилась ОДИН раз, на
    паузу или на закрытие сессии. Если связь на телефоне умирала, TEARDOWN
    не приходил вовсе, сессия закрывалась по молчанию -- и до этого момента
    в Jellyfin не было ничего. Теперь место свежее с точностью до осмотра.
    """
    if not item_id:
        return
    jf_doklad("/Progress", item_id, seconds,
              {"CanSeek": True, "IsPaused": False,
               "PlayMethod": "Transcode"}, kto)


def skazat_jellyfin(item_id, seconds, kto=""):
    """Просмотр кончился -- итоговая отметка места.

    Галочку «просмотрено» ставим не мы: Jellyfin сам решает по этой
    отметке, досмотрено ли до конца (у него порог -- девять десятых
    длительности). Поэтому здесь важно одно -- чтобы число было честным.
    """
    if not item_id or seconds <= 1.0:
        return
    code = jf_doklad("/Stopped", item_id, seconds, None, kto)
    if code:
        note("Jellyfin: отметил %.0f с по записи %s (ответ %d, %s)"
             % (seconds, item_id[:8], code, chey(kto)))


def home_address(ip):
    """Адрес из домашней сети?

    Нужно ради переходного времени: на телефоне уже стоит сборка, которая
    токена в адрес не кладёт. Дома ей верим -- туда с улицы не попасть. Из
    любой чужой сети без токена не пускаем никого.
    """
    if ip.startswith("127.") or ip.startswith("10.") or ip.startswith("192.168."):
        return True
    spotted = re.match(r"^172\.(\d+)\.", ip)
    return bool(spotted) and 16 <= int(spotted.group(1)) <= 31


def item_title(item_id):
    """Как назвать запись в описании потока.

    Это единственная надпись, которую плеер показывает поверх картинки, и
    до сих пор там стояло слово «Proba» из заготовки описания -- владелец
    видел его на экране вместо названия серии.

    Для серии получается «3x01 Название»: ровно то же, что человек выбирал в
    списке приложения, и короткое -- заголовок на экране E90 обрезается
    примерно на двадцати знаках. Если Jellyfin почему-то не ответил,
    возвращается пустая строка, и заготовка остаётся прежней: название
    приятно, но ради него ломать воспроизведение нельзя.
    """
    try:
        address = "%s/Items/%s?api_key=%s" % (
            JELLYFIN, item_id, jellyfin_token())
        with urllib.request.urlopen(address, timeout=8) as answer:
            data = json.loads(answer.read().decode("utf-8"))
    except Exception as error:
        note("название записи не получено: %s" % error)
        return ""

    name = (data.get("Name") or "").strip()
    season = data.get("ParentIndexNumber")
    number = data.get("IndexNumber")
    if data.get("Type") == "Episode" and season is not None and number is not None:
        return ("%dx%02d %s" % (season, number, name)).strip()
    return name


def item_url(item_id):
    return "%s/Videos/%s/stream?static=true&api_key=%s" % (
        JELLYFIN, item_id, jellyfin_token())


def template_for(fps, item_id, ekran=None):
    """Описание-шаблон для этой частоты кадров и этого экрана.

    Строится один раз на сочетание: описание зависит только от размера
    картинки и частоты кадров, а не от записи. Поэтому второй телефон с тем
    же экраном получит готовое, без ожидания.
    """
    width, height = ekran or EKRAN
    name = "shablon-%d-%dx%d" % (fps, width, height)
    if name in TEMPLATE_FPS:
        return name

    VARIANTS[name] = (None, "va", EVENLY)
    TWEAKS[name] = {"relay": True, "pss": True, "like_others": True,
                    "audio_pkt": 400, "jellyfin": item_id,
                    "video_plan": (speed_for(width, height),
                                   scale_to(width, height), fps),
                    "audio_opts": TARGET_AUDIO}
    note("собираю описание-шаблон: %d кадров, экран %dx%d, %d кбит/с"
         % (fps, width, height, speed_for(width, height)))
    text = build_sdp(name, None, "va")
    if not text:
        note("шаблон %s не собрался" % name)
        return None
    SDP[name] = text
    TEMPLATE_FPS[name] = True
    return name


def prepare_item(item_id, ekran=None):
    """Сделать запись Jellyfin вариантом потока. Возвращает имя варианта.

    Имя -- `jf-<запись>`, одним участком пути и без особых знаков: двоеточие
    или собачка в адресе разборщик RealPlayer читает по-своему, на этом уже
    обожглись (см. выше про `auto@754`).
    """
    width, height = ekran or EKRAN
    name = "jf-" + item_id.lower()
    if (width, height) != tuple(EKRAN):
        # Экран пишется в имя варианта: описание у разных экранов разное, а
        # одна и та же запись может идти сразу на два телефона.
        name += "-%dx%d" % (width, height)
    if name in SDP:
        return name

    source = item_url(item_id)
    duration, _width, _height, found = describe_file(source)
    if not duration:
        note("запись %s не опознана -- нет длительности" % item_id)
        return None
    fps = max(5, int(round(min(found or 15.0, 25.0))))

    template = template_for(fps, item_id, (width, height))
    if not template:
        return None

    # От шаблона отличается только длительностью. Имя дорожек подставляется
    # при выдаче описания, поэтому переписывать их не надо.
    text = re.sub(r"a=range:npt=0-[0-9.]+",
                  "a=range:npt=0-%.3f" % duration, SDP[template])

    title = item_title(item_id)
    if title:
        # Переводов строки в названии быть не должно: описание разбирается
        # построчно, и одна лишняя строка ломает его целиком.
        title = title.replace("\r", " ").replace("\n", " ")
        text = re.sub(r"^s=.*$", "s=" + title, text, count=1, flags=re.MULTILINE)

    VARIANTS[name] = (None, "va", EVENLY)
    TWEAKS[name] = dict(TWEAKS[template])
    TWEAKS[name]["jellyfin"] = item_id
    if PROBA_TCP:
        TWEAKS[name]["refuse_udp"] = True
    SDP[name] = text
    LENGTHS[name] = duration
    CONTROLS[name] = CONTROLS[template]
    note("запись %s готова: %.1f с, %d кадров" % (item_id, duration, fps))
    return name


class Session(object):
    """Один разговор с плеером: какой вариант, какие порты и что мы шлём."""

    def __init__(self):
        self.variant = DEFAULT
        self.video_port = 0
        self.audio_port = 0
        # Названия дорожек, которые плеер действительно настроил. В ответе на
        # PLAY можно называть только их: ссылка на дорожку, которой у плеера
        # нет, делает весь ответ негодным -- RealPlayer на это отвечает
        # «неверный адрес сервера» и сразу рвёт сессию.
        self.tracks = []
        self.streamer = None
        self.deadline = None
        self.relays = []
        # Вид дорожки -> порт, который слушает посредник. Заполняется на SETUP:
        # номер надо назвать плееру в ответе, значит занять порт надо раньше,
        # чем запустится ffmpeg.
        self.relay_ports = {}
        # Вид дорожки -> её счёт номеров и меток времени.
        self.counters = {}
        # Пропуск предъявлен и проверен.
        self.pass_ok = False
        # Токен зрителя -- тот, что приложение положило в адрес.
        #
        # Нужен не для пропуска (для него есть key_valid), а для
        # ДОКЛАДОВ Jellyfin. Раньше место отмечалось токеном из
        # token.txt, то есть всегда одним и тем же пользователем. Если
        # на телефоне вошли под другим -- а так оно и есть, когда
        # смотрит семья, -- место честно сохранялось в чужую карточку,
        # и ни телефон, ни компьютер его не видели. Докладывать должен
        # тот, кто смотрит.
        self.zritel = ""
        # Номер канала -> посредник, если передаём по TCP. Нужен, чтобы
        # отчёты плеера, пришедшие по соединению, попали туда же, куда
        # попадали бы из UDP.
        self.by_channel = {}
        # Где мы в записи, в секундах. Меняется при PAUSE и при перемотке.
        self.position = 0.0
        # Начало, заданное в адресе (`/auto@754`). Хранится отдельно от
        # position потому, что плееры почти всегда присылают в PLAY своё
        # `Range: npt=0.000-` -- не как просьбу о перемотке, а просто «с
        # начала». Это затирало заданное нами начало, и возможность не
        # работала бы вовсе.
        self.offset = 0.0
        self.started_at = None
        # Какие номер и метка обещаны плееру в ответе на PLAY.
        self.expected = {}
        # Для наблюдения за ходом: сколько пакетов было в прошлый осмотр.
        self.moved_before = -1
        self.watchdog = None
        # С какого места записи начался текущий запуск. Нужно, чтобы
        # отличить просмотр от промаха по кнопке: см. MINIMUM.
        self.nachato = 0.0
        # Докладывали ли Jellyfin место за этот запуск.
        #
        # Докладывать несколько раз нельзя, и вот почему. Один клиент может
        # держать ДВА разговора сразу: плеер открывает новое соединение, не
        # закрыв прежнее, и прежний обработчик ещё две минуты сидит в ожидании
        # (сервер многопоточный, никому он при этом не мешает). Когда он
        # наконец закрывается, он докладывает своё место -- то есть старое,
        # уже перекрытое. В Jellyfin «продолжить просмотр» от этого прыгает
        # НАЗАД: человек досмотрел до двенадцатой минуты, а ему предлагают
        # продолжить с девятой.
        #
        # Такое же удвоение выходило и на ровном месте: при TEARDOWN и при
        # истечении ожидания `release()` вызывается дважды -- из разбора
        # команды и из `finally`.
        #
        # Поэтому: один доклад на запуск. Новый запуск признак снимает, так
        # что пауза с продолжением докладывает честно оба раза.
        self.dolozhil = False

    def start(self, client_ip):
        # Учёт запущенного потока и само гашение разделены нарочно: если
        # гасить внутри stop(), тот же замок берётся дважды и сервер встаёт.
        with RUNNING_LOCK:
            previous = RUNNING["session"]
            RUNNING["session"] = self

        if previous is not None and previous is not self:
            note("гашу прежний поток")
            previous.stop()

        self.dolozhil = False

        # Гасится только ffmpeg: посредники этой сессии подняты на SETUP, и
        # ронять их здесь нельзя -- плееру уже названы их порты.
        self.stop_streamer()

        filename, streams, feeding = VARIANTS[self.variant]
        if feeding == EVENLY:
            feeding = rovno()
        source = source_of(self.variant, filename)
        tweaks = TWEAKS.get(self.variant, {})
        plan = tweaks.get("video_plan")
        if plan:
            # Частота кадров берётся из источника, а не назначается. Третье
            # число, если оно есть, -- потолок: «не выше столько кадров».
            speed, scale = plan[0], plan[1]
            ceiling = plan[2] if len(plan) > 2 else 25.0
            video_opts = target_video(fps_for(source, ceiling), speed, scale)
            note("частота кадров по источнику: %s" % video_opts[
                video_opts.index("-r") + 1])
        else:
            video_opts = tweaks.get("video_opts") or ["-c:v", "copy"]
        audio_opts = tweaks.get("audio_opts") or ["-c:a", "copy"]
        # Запись из Jellyfin и так длинная -- по кругу её гонять не надо.
        loop = [] if tweaks.get("jellyfin") else ["-stream_loop", "-1"]

        # Откуда начинать. Не ноль, если плеер попросил перемотку или
        # продолжает после PAUSE.
        seek = ["-ss", "%.3f" % self.position] if self.position > 0.05 else []

        # Посредникам -- новый отсчёт: ffmpeg начнёт со своих случайных чисел,
        # а наружу номера и время должны продолжиться без разрыва.
        # Сначала выбросить остатки прошлого запуска, потом начинать новый
        # отсчёт: иначе последний пакет старого ffmpeg задал бы точку отсчёта
        # времени, и поток разъехался бы после паузы или перемотки.
        for relay in self.relays:
            relay.drop_leftovers(0.3)
        if self.relays:
            time.sleep(0.35)

        # Рубеж у дорожек общий. Каждая отдана по-своему далеко -- звук
        # обычно впереди видео, потому что звуковой кадр кодируется быстрее.
        # Если каждая продолжит от своего значения, содержимое у них пойдёт
        # с одного места записи, а метки времени -- с разных, и плеер отложит
        # звук на эту разницу. Телефон присылает PAUSE и PLAY на каждое
        # изменение громкости, так что разницы складываются: за час звук
        # отстал на две-три секунды.
        #
        # Берётся самое дальнее место: назад метки времени идти не должны.
        # Обе дорожки сдвигаются одинаково, поэтому сведение не страдает.
        rubezh = self.position
        if self.counters:
            # Печатается нарочно: иначе нельзя отличить «рубеж применён» от
            # «правка лежит на сервере, но до этой ветки дело не дошло».
            note("продолжаю с %.2f с; было отдано: %s"
                 % (rubezh, ", ".join("%s=%.2f" % (kind, track.emitted())
                                      for kind, track
                                      in sorted(self.counters.items()))))
        for track in self.counters.values():
            track.new_run(rubezh)
        self.started_at = time.time()
        self.nachato = rubezh

        # Доклад о начале -- отдельным потоком: Jellyfin может задуматься на
        # секунду, а плеер в это время ждёт ответа на PLAY.
        item = tweaks.get("jellyfin")
        if item:
            threading.Thread(target=skazat_nachalo,
                             args=(item, rubezh, self.zritel),
                             daemon=True).start()

        # Числа для RTP-Info снимаются ЗДЕСЬ, до запуска ffmpeg. Иначе он
        # успевает отправить пару пакетов, пока составляется ответ, и
        # обещанный номер оказывается на 1-3 впереди настоящего.
        self.expected = dict((kind, track.expect())
                             for kind, track in self.counters.items())
        flags = TWEAKS.get(self.variant, {}).get("rtpflags")
        extra = ["-rtpflags", flags] if flags else []
        command = ([FFMPEG, "-hide_banner", "-loglevel", "info"]
                   + feeding + loop + seek + ["-i", source])

        # Номера типов полезной нагрузки задаются явно. У ffmpeg каждый выход
        # нумеруется с 96 заново, поэтому звук уходил как 96, а в описании
        # потока он объявлен как 97 -- плеер такой звук просто не узнаёт.
        muxer = TWEAKS.get(self.variant, {}).get("muxer")
        if muxer:
            # Обе дорожки одним выходом: внутри транспортный поток.
            command += ["-map", "0:v:0", "-map", "0:a:0", "-c", "copy",
                        "-ssrc", str(VIDEO_SSRC), "-f", muxer,
                        "rtp://%s:%d?localrtpport=%d&localrtcpport=%d"
                        % (client_ip, self.video_port, VIDEO_FROM, VIDEO_FROM + 1)]
            note("вариант %s (%s, одной дорожкой): -> %s"
                 % (self.variant, " ".join(feeding), self.video_port))
            note("команда: " + " ".join(command))
            errors = io.open(FFMPEG_ERR, "ab")
            self.streamer = subprocess.Popen(command, stdout=subprocess.DEVNULL,
                                             stderr=errors)
            threading.Timer(2.0, self.report).start()
            self.start_watching()
            self.deadline = threading.Timer(LIMIT_SECONDS, self.expire)
            self.deadline.daemon = True
            self.deadline.start()
            return

        # Через посредник или напрямую. Посредник переписывает номера пакетов
        # и метки времени так, чтобы они начинались с 1 и 0 -- тогда заголовок
        # RTP-Info в ответе на PLAY становится правдой. Клиент 3GPP сводит по
        # нему дорожки между собой, и для двух дорожек это решает всё.
        # При передаче внутри соединения RTSP посредник обязателен всегда:
        # ffmpeg умеет отдавать только в UDP, а превращает пакеты в кадры
        # именно посредник. Без этой проверки поток ушёл бы на порт плеера,
        # которого при TCP не существует вовсе.
        through = TWEAKS.get(self.variant, {}).get("relay") or bool(self.by_channel)

        # Признак настроенной дорожки. Обычно это порт, который плеер назвал
        # в SETUP. При передаче внутри соединения RTSP портов нет вовсе, и
        # признаком служит посредник: он занял каналы ещё на SETUP. Без этого
        # ffmpeg получал команду без единого выхода и умирал с «At least one
        # output file must be specified» -- в журнале это выглядело как
        # «ffmpeg умер сразу, код 1», причём переговоры проходили успешно.
        video_ready = self.video_port or "video" in self.relay_ports
        audio_ready = self.audio_port or "audio" in self.relay_ports

        if video_ready and "v" in streams:
            command += (["-map", "0:v:0"] + video_opts
                        + ["-payload_type", "96", "-ssrc", str(VIDEO_SSRC)])
            # Предел пакета -- чтобы ни один не дробился в мобильной сети.
            # Ставится у выхода, а не у входа: это настройка упаковки.
            limit = TWEAKS.get(self.variant, {}).get("video_pkt") or VIDEO_PKT
            if limit:
                command += ["-pkt_size", str(limit)]
            command += extra + ["-f", "rtp", self.sink("video", client_ip,
                                                       self.video_port, through)]
        if audio_ready and "a" in streams:
            command += (["-map", "0:a:0"] + audio_opts
                        + ["-payload_type", "97", "-ssrc", str(AUDIO_SSRC)])
            limit = TWEAKS.get(self.variant, {}).get("audio_pkt")
            if limit:
                command += ["-pkt_size", str(limit)]
            command += extra + ["-f", "rtp", self.sink("audio", client_ip,
                                                       self.audio_port, through)]

        if self.by_channel:
            note("вариант %s (%s) внутри соединения RTSP: каналы %s, с %.1f с"
                 % (self.variant, " ".join(feeding),
                    "-".join(str(c) for c in sorted(self.by_channel)),
                    self.position))
        else:
            note("вариант %s (%s)%s: видео -> %s, звук -> %s, с %.1f с"
                 % (self.variant, " ".join(feeding),
                    " через посредник" if through else "",
                    self.video_port, self.audio_port, self.position))
        note("команда: " + hide_token(" ".join(command)))

        errors = io.open(FFMPEG_ERR, "ab")
        self.streamer = subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=errors)

        # Проверка, что ffmpeg действительно пошёл. Молча умерший ffmpeg
        # выглядит на телефоне как «висит на пустой загрузке», и без этой
        # строки причину приходится искать по всему журналу.
        threading.Timer(2.0, self.report).start()
        self.start_watching()

        # Предел длины: брошенный поток не должен литься вечно.
        self.deadline = threading.Timer(LIMIT_SECONDS, self.expire)
        self.deadline.daemon = True
        self.deadline.start()

    def sink(self, kind, client_ip, client_port, through):
        """Куда ffmpeg отправляет дорожку: посреднику или прямо плееру.

        Через посредник ffmpeg выбирает себе исходящий порт сам: раньше он
        задавался жёстко, и при наложении сессий это молча ломалось. Обратный
        адрес посредник узнаёт из первого же пакета.
        """
        if through:
            return "rtp://%s:%d" % (LOCAL, self.relay_ports[kind])
        mine = AUDIO_FROM if kind == "audio" else VIDEO_FROM
        return ("rtp://%s:%d?localrtpport=%d&localrtcpport=%d"
                % (client_ip, client_port, mine, mine + 1))

    def open_relay(self, kind, client_ip, client_port):
        """Занять пару портов и поднять посредников для одной дорожки.

        Вызывается на SETUP, а не на PLAY: номер порта отправки надо назвать
        плееру в ответе на SETUP, значит занять его надо раньше. Порт выдаёт
        система -- жёсткие номера приводили к тому, что сокет прошлой сессии
        перехватывал пакеты новой, и дорожка молча не приходила.
        """
        rtp, rtcp, port = bind_pair()
        # Память о точке отсчёта общая для данных и отчётов: иначе RTP и RTCP
        # назвали бы плееру разное время, и сведение сломалось бы снова.
        track = Track(chasy(kind))
        self.relays.append(Relay(track, rtp, client_ip, client_port,
                                 rtcp=False, note=note))
        self.relays.append(Relay(track, rtcp, client_ip, client_port + 1,
                                 rtcp=True, note=note))
        self.relay_ports[kind] = port
        self.counters[kind] = track
        note("посредник (%s): слушаю %d-%d, отдаю плееру на %d-%d"
             % (kind, port, port + 1, client_port, client_port + 1))
        return port

    def open_relay_tcp(self, kind, channels, writer):
        """То же самое, но пакеты уходят внутрь соединения RTSP.

        Зачем это вообще. При обычной работе RTP идёт по UDP на порты,
        которые плеер назвал в SETUP. Дома это работает, а из чужой сети --
        нет: телефон за чужим роутером входящий UDP не получит, и проброс
        дома этого не лечит -- беда на его стороне. Здесь же всё идёт по тому
        самому соединению, которое плеер открыл сам: один TCP-порт 554 и
        никаких входящих соединений.

        Сокеты всё равно нужны: ffmpeg умеет отдавать только в UDP, и он по
        прежнему отдаёт посреднику на 127.0.0.1. Меняется только последний
        шаг -- куда кладётся готовый пакет.
        """
        data_channel, report_channel = channels
        rtp, rtcp, port = bind_pair()
        track = Track(chasy(kind))
        first = Relay(track, rtp, "0.0.0.0", 0, rtcp=False, note=note,
                      deliver=lambda packet: writer(data_channel, packet))
        second = Relay(track, rtcp, "0.0.0.0", 0, rtcp=True, note=note,
                       deliver=lambda packet: writer(report_channel, packet))
        self.relays.append(first)
        self.relays.append(second)
        # Отчёты плеера придут по соединению, и разбирать их будет тот,
        # кто занимается этой парой каналов.
        self.by_channel[data_channel] = first
        self.by_channel[report_channel] = second
        self.relay_ports[kind] = port
        self.counters[kind] = track
        note("посредник (%s) по TCP: слушаю %d-%d, отдаю в каналы %d-%d"
             % (kind, port, port + 1, data_channel, report_channel))
        return port

    def expire(self):
        if self.streamer and self.streamer.poll() is None:
            note("прошло %d с -- гашу поток, чтобы не лить вечно" % LIMIT_SECONDS)
            self.stop()

    def report(self):
        if self.streamer is None:
            return
        code = self.streamer.poll()
        if code is None:
            note("поток идёт")
        else:
            note("ВНИМАНИЕ: ffmpeg умер сразу, код %s -- смотрите rtsp-ffmpeg.err" % code)

    def watch(self):
        """Каждые полминуты -- сколько пакетов ушло плееру.

        Нужно затем, что «поток идёт» говорит только о живом ffmpeg. Один раз
        ffmpeg бодро писал «speed=1.01x» две минуты, а посредник к тому
        времени был мёртв, и телефон не получал ничего: со стороны телефона это
        вечная загрузка, а в журнале -- ни одной строки о беде. Теперь замерший
        счётчик виден сразу.
        """
        if self.streamer is None or self.streamer.poll() is not None:
            return
        moved = sum(r.passed for r in self.relays)
        hiccups = sum(r.hiccups for r in self.relays)
        undelivered = sum(r.undelivered for r in self.relays)
        parts = ["ушло пакетов: %s"
                 % ", ".join("%s=%d" % (r.port, r.passed) for r in self.relays)]
        if moved == self.moved_before:
            parts.append("ПОТОК СТОИТ: за полминуты ни одного пакета")
        if hiccups:
            # С разбивкой по портам: сумма не говорит, КАКОЙ путь отбивается,
            # а это разные беды. Данные бьются -- мы шлём не туда, куда плеер
            # на самом деле слушает. Отчёты бьются -- плеер просто не держит
            # для них сокета, и это терпимо.
            parts.append("ошибок приёма пережито: %d (%s)"
                         % (hiccups, ", ".join("%s=%d" % (r.port, r.hiccups)
                                               for r in self.relays
                                               if r.hiccups)))
        if undelivered:
            parts.append("не доставлено: %d" % undelivered)
        # Расхождение дорожек. Главная мера для беды «звук отстаёт от
        # картинки»: здесь видно, расходятся ли дорожки У НАС, или они идут в
        # ногу, а разъезжается всё уже на телефоне. На глаз этого не отличить
        # никак, а это два совершенно разных ремонта.
        video, audio = self.counters.get("video"), self.counters.get("audio")
        if video is not None and audio is not None:
            otdano_v, otdano_a = video.emitted(), audio.emitted()
            parts.append("отдано: видео %.1f с, звук %.1f с, расхождение "
                         "%+.2f с" % (otdano_v, otdano_a, otdano_a - otdano_v))

        # Что плеер прислал нам сам. Для порта ДАННЫХ это и есть ответ на
        # вопрос, открывается ли дорога через чужой роутер.
        parts.append("от плеера пришло: %s"
                     % ", ".join("%s=%d" % (r.port, r.heard)
                                 for r in self.relays))
        for relay in self.relays:
            if relay.complaint:
                share, lost, _ = relay.complaint
                parts.append("плеер на %s: потери %.1f%%, всего %d"
                             % (relay.port, share, lost))
        self.moved_before = moved
        note("; ".join(parts))

        # Заодно -- доклад Jellyfin о ходе просмотра. Раз в полминуты: чаще
        # незачем, а реже значит терять место при обрыве связи.
        item = TWEAKS.get(self.variant, {}).get("jellyfin")
        if item:
            threading.Thread(target=skazat_hod,
                             args=(item, self.otmetka(), self.zritel),
                             daemon=True).start()

        self.watchdog = threading.Timer(30.0, self.watch)
        self.watchdog.daemon = True
        self.watchdog.start()

    def delivered(self):
        """Докуда поток отдан на самом деле, в секундах записи.

        Это одно число служит сразу трём делам: место для продолжения после
        паузы, точка отсчёта времени для следующего запуска и отметка для
        Jellyfin. Нарочно одно, и вот почему.

        Раньше их было три, и каждое врало по-своему:

        * место считалось по НАСТЕННЫМ часам. Часы идут и тогда, когда поток
          встал, а плеер молчит, -- место уезжало вперёд показанного.
        * отметка для Jellyfin прибавляла время запуска второй раз и выходила
          ровно вдвое больше (пауза на 19 с -> отметка 39).
        * точка отсчёта бралась у каждой дорожки своя, и дорожки разъезжались.

        Главное же -- место и точка отсчёта были РАЗНЫМИ числами, а это и
        есть причина повтора звука на возобновлении. Дорожки отданы не
        одинаково далеко: звук уходит вперёд видео, потому что звуковой кадр
        дёшев. Если продолжать с места, которое позади самой дальней дорожки,
        то содержимое между этими двумя точками уходит ВТОРОЙ раз -- человек
        слышит, как повторяется фраза. А метки времени при этом не могут идти
        назад, значит повторённое содержимое получает более поздние метки, и
        звук отстаёт от картинки ровно на эту разницу.

        Теперь место = самая дальняя отданная дорожка. Продолжаем оттуда,
        откуда и остановились: повторять нечего. И поскольку точка отсчёта --
        то же число, метка времени пакета всегда равна месту записи в нём.
        Отстающая дорожка при этом перескакивает вперёд на разницу (у видео
        это доли секунды), и перескок честный: в пропущенных метках времени и
        правда ничего не отдано.
        """
        places = [track.emitted() for track in self.counters.values()]
        if places:
            return max(places)
        if self.started_at is not None:
            return self.position + max(0.0, time.time() - self.started_at)
        return self.position

    def resume_point(self):
        """С какого места записи продолжать после паузы.

        По САМОЙ БЛИЖНЕЙ из отданных дорожек, а не по самой дальней. Если
        начать с дальней, то ближняя получит разрыв в метках времени -- для
        неё этого содержимого не отдавали вовсе. Разрыв плеер может соблюсти,
        а может и не соблюсти; у кого не соблюдает, у того картинка уезжает
        вперёд звука ровно на разрыв, и так на каждой паузе.

        Если же начать с ближней, то дальняя получит перехлёст -- содержимое,
        которое уже отдала. Это поправимо: перехлёст выбрасывает сам
        посредник (см. `Track.new_run`). Поэтому берём ближнюю: её беда
        неустранима, а беда дальней -- устранима.

        Дорожки, не отдавшие в этом запуске ни пакета, не считаются: иначе
        одна молчащая дорожка отмотала бы просмотр к нулю.
        """
        otdali = [track.emitted() for track in self.counters.values()
                  if track.since_run() > 0]
        if otdali:
            return min(otdali)
        return self.delivered()

    def hold(self):
        """Приостановить: запомнить место и погасить ffmpeg.

        Посредники остаются -- плееру уже названы их порты, и после PLAY поток
        должен продолжиться в те же.
        """
        if self.started_at is not None:
            self.position = self.resume_point()
            self.started_at = None
        note("пауза на %.1f с записи" % self.position)
        self.stop_streamer()
        self.dolozhit()

    def start_watching(self):
        if self.watchdog is not None:
            self.watchdog.cancel()
        self.moved_before = -1
        self.watchdog = threading.Timer(30.0, self.watch)
        self.watchdog.daemon = True
        self.watchdog.start()

    def stop_streamer(self):
        """Погасить только ffmpeg, посредников не трогать."""
        if self.watchdog is not None:
            self.watchdog.cancel()
            self.watchdog = None
        if self.deadline is not None:
            self.deadline.cancel()
            self.deadline = None
        if self.streamer and self.streamer.poll() is None:
            self.streamer.terminate()
            try:
                self.streamer.wait(timeout=3)
            except Exception:
                self.streamer.kill()
        self.streamer = None

    def otmetka(self):
        """Место для Jellyfin -- с поправкой на молчание плеера.

        Отданное и показанное -- не одно и то же. Сессия закрывается через
        две минуты после последнего признака жизни, а ffmpeg всё это время
        кормит посредника в пустоту: отданное уезжает вперёд показанного
        ровно на длину молчания. Без поправки итоговая отметка уводила
        просмотр на две минуты вперёд -- то есть на следующую сцену.

        Отчёты плеера -- единственный признак, по которому видно, когда он
        слушал последний раз. Порог нужен потому, что в обычной работе
        отчёты приходят раз в несколько секунд, и вычитать их возраст --
        значит каждый раз отматывать отметку на пустяк.
        """
        gde = self.delivered()
        molchit = [relay.silent_for() for relay in self.relays
                   if relay.rtcp and relay.silent_for() is not None]
        if molchit and min(molchit) > 10.0:
            note("поправка на молчание: отдано %.0f с, плеер молчит %.0f с"
                 % (gde, min(molchit)))
            gde -= min(molchit)
        return max(0.0, gde)

    def dolozhit(self):
        """Отдать Jellyfin место, на котором остановились.

        Отдельным потоком: Jellyfin может задуматься на секунду, а мы в это
        время должны отвечать плееру -- он ждёт ответа на ту же PAUSE.
        """
        item = TWEAKS.get(self.variant, {}).get("jellyfin")
        if not item:
            return
        if self.dolozhil:
            # Уже доложили за этот запуск. Второй доклад несёт то же или
            # устаревшее место и может только испортить отметку.
            return
        self.dolozhil = True
        gde = self.otmetka()
        if gde - self.nachato < MINIMUM:
            # Не отметка, а промах по кнопке. Отметить -- значит затереть
            # хорошее место плохим; см. MINIMUM.
            note("не отмечаю: за запуск отдано %.1f с -- это не просмотр"
                 % max(0.0, gde - self.nachato))
            return
        threading.Thread(target=skazat_jellyfin, args=(item, gde, self.zritel),
                         daemon=True).start()

    def tishina(self):
        """Давно ли молчит плеер на путях потока -- для разбора обрывов.

        Сессию закрывает молчание разговора по TCP, а это совсем другой путь,
        чем поток. Телефон в чужой сети может потерять один путь и сохранить
        другой, и тогда закрытие сессии -- наша ошибка, а не обрыв связи.
        Чтобы это было видно сразу, а не вычислялось потом по косвенным
        признакам, при закрытии по молчанию печатается, давно ли молчит плеер.

        Но признак жизни здесь -- ТОЛЬКО отчёты. Сперва печатались все четыре
        пути подряд, и это вводило в заблуждение: в порты ДАННЫХ плеер шлёт
        ровно один пакет за всю сессию -- пробивку пути, -- и больше не шлёт
        никогда. Значит их «молчание» всегда равно возрасту сессии и не
        говорит ни о чём. В первом же разборе это чуть не было прочитано как
        «данные живы, а отчёты умерли».

        Поэтому отчёты показываются молчанием, а данные -- числом пробивок:
        там важно не «давно ли», а «приходило ли вообще».
        """
        otchety, dannye = [], []
        for relay in self.relays:
            if relay.rtcp:
                quiet = relay.silent_for()
                otchety.append("%s=%s" % (relay.port,
                                          "ни разу" if quiet is None
                                          else "%.0f с" % quiet))
            else:
                dannye.append("%s=%d" % (relay.port, relay.heard))
        parts = []
        if otchety:
            parts.append("молчат отчёты: " + ", ".join(otchety))
        if dannye:
            parts.append("пробивок в данные: " + ", ".join(dannye))
        return "; ".join(parts) if parts else "посредников не было"

    def stop(self):
        """Погасить всё: и ffmpeg, и посредников."""
        self.dolozhit()
        self.stop_streamer()
        for relay in self.relays:
            relay.stop()
        if self.relays:
            note("посредники остановлены, пакетов пропущено: %s"
                 % ", ".join("%s=%d" % (r.port, r.passed) for r in self.relays))
            note("от плеера за сессию: %s"
                 % ", ".join("%s=%d%s"
                             % (r.port, r.heard,
                                "" if r.heard_from is None
                                else " (с %s:%d)" % r.heard_from)
                             for r in self.relays))
            hiccups = sum(r.hiccups for r in self.relays)
            undelivered = sum(r.undelivered for r in self.relays)
            if hiccups or undelivered:
                note("за сессию: ошибок приёма пережито %d, не доставлено %d"
                     % (hiccups, undelivered))
            for relay in self.relays:
                if relay.complaint:
                    share, lost, jitter = relay.complaint
                    note("последняя жалоба плеера (%s): потери %.1f%%, "
                         "всего %d, дрожание %d" % (relay.port, share, lost, jitter))
        self.relays = []
        self.relay_ports = {}
        self.by_channel = {}

    def release(self):
        """Снять себя с учёта -- при закрытии сессии."""
        self.stop()
        with RUNNING_LOCK:
            if RUNNING["session"] is self:
                RUNNING["session"] = None


# Замок-пустышка: на случай ответа до того, как появился настоящий.
DUMMY_LOCK = threading.Lock()


class Rtsp(socketserver.StreamRequestHandler):

    # Плеер сам шлёт OPTIONS как «я жив», так что молчание дольше двух минут
    # означает, что он отвалился или завис. Без этого зависший телефон держит
    # сессию открытой, а с ней и порты отправки.
    timeout = 120

    def handle(self):
        client_ip = self.client_address[0]
        session = Session()
        # Замок на запись в соединение и ссылка на сессию: нужны для передачи
        # по TCP, где данные и разговор делят один сокет.
        self.writing = threading.Lock()
        self.playing = session
        note("--- подключился %s ---" % client_ip)

        try:
            while True:
                request = self.read_request()
                if not request:
                    break

                head = request[0].split()
                method = head[0] if head else ""
                url = head[1] if len(head) > 1 else "*"
                sequence = self.header(request, "CSeq") or "1"

                note("%s %s" % (method, url))

                if method == "OPTIONS":
                    self.reply(sequence, extra=["Public: OPTIONS, DESCRIBE, SETUP, PLAY, PAUSE, TEARDOWN"])

                elif method == "DESCRIBE":
                    session.variant, start, key = self.route(url)
                    # Проверка СРАЗУ: до описания, а значит и до ffmpeg.
                    if not self.allowed(session.variant, key, client_ip):
                        self.reply(sequence, status="401 Unauthorized")
                        break
                    session.pass_ok = True
                    if key:
                        session.zritel = key
                    if start:
                        session.offset = start
                        session.position = start
                        note("в адресе просят начать с %.1f с" % start)
                    if session.variant not in SDP:
                        note("описание варианта %s ещё не готово -- отказ"
                             % session.variant)
                        self.reply(sequence, status="503 Service Unavailable")
                        continue
                    # Себя называем ТЕМ адресом, по которому к нам пришли.
                    #
                    # В описании потока адреса дорожек -- полные, и плеер по
                    # ним и ходит. Раньше туда подставлялся наш адрес в
                    # локальной сети. Дома это совпадало и работало, а из
                    # чужой сети телефон получил бы адрес вида 192.168.x.x,
                    # который у него ведёт в его собственную квартиру, и
                    # дорожки не настроились бы вовсе. Хост из запроса верен
                    # всегда: именно по нему плеер до нас и добрался.
                    body = SDP[session.variant].format(
                        server=self.host_of(url) or self.local_ip(),
                        client=client_ip,
                        variant=session.variant).encode("utf-8")
                    note("отдаю описание варианта %s (%d байт)" % (session.variant, len(body)))
                    self.reply(sequence, extra=[
                        "Content-Type: application/sdp",
                        "Content-Base: %s/" % url,
                        "Content-Length: %d" % len(body)], body=body)

                elif method == "SETUP":
                    # Токен снимаем и здесь, а не только на DESCRIBE:
                    # плеер может открыть новое соединение между
                    # описанием и настройкой дорожек, и тогда сессия
                    # осталась бы без токена зрителя -- доклад ушёл бы
                    # служебным, то есть мимо того, кто смотрит.
                    session.variant, _start, key = self.route(url)
                    if key:
                        session.zritel = key
                    transport = self.header(request, "Transport") or ""
                    note("плеер просит транспорт: %s" % transport)

                    # Профиль берётся из просьбы плеера, а не задаётся жёстко.
                    # Раньше в ответе всегда стояло «RTP/AVP», и для
                    # транспортного потока плеер отваливался сразу после SETUP,
                    # не дойдя до PLAY: он просит другой профиль (MP2T/AVP), а
                    # получал не тот, что просил.
                    profile = transport.split(",")[0].split(";")[0].strip()
                    if not profile:
                        profile = "RTP/AVP"

                    refuse = TWEAKS.get(session.variant, {}).get("refuse_udp")
                    asked_tcp = "TCP" in profile.upper()
                    # Навязывание: плеер просил UDP, а мы отвечаем согласием на
                    # передачу внутри соединения, будто он сам её и просил.
                    forced = bool(refuse) and not asked_tcp and PROBA_TCP >= 2

                    if refuse and not asked_tcp and not forced:
                        # Отказ с подсказкой: по стандарту заголовка Transport
                        # в ответе 461 быть не обязано, но некоторые плееры его
                        # читают и повторяют запрос уже с нашим транспортом.
                        note("вариант-разведка: отказываю на UDP и подсказываю "
                             "передачу внутри соединения")
                        self.reply(sequence, status="461 Unsupported transport",
                                   extra=["Transport: RTP/AVP/TCP;unicast;"
                                          "interleaved=0-1"])
                        continue

                    by_tcp = asked_tcp or forced
                    if forced:
                        # В ответе транспорт называется своим именем, иначе
                        # плеер решит, что получил согласие на UDP.
                        profile = "RTP/AVP/TCP"
                        note("вариант-разведка: плеер просил UDP -- навязываю "
                             "передачу внутри соединения")

                    ports = re.search(r"client_port=(\d+)-(\d+)", transport)
                    low = int(ports.group(1)) if ports else 0

                    control = url.rstrip("/").split("/")[-1]
                    kind = None
                    for suffix, what in CONTROLS.get(session.variant, []):
                        if suffix == control:
                            kind = what
                            break

                    if kind is None:
                        # Плеер настраивает не дорожку, а всю сессию. Чужие
                        # серверы отвечают на это отказом 459, и правильно:
                        # порты задаются по дорожке, а не на всё сразу.
                        note("SETUP не на дорожку, а на сессию -- отказ 459")
                        self.reply(sequence,
                                   status="459 Aggregate operation not allowed")
                        continue

                    if kind == "audio":
                        session.audio_port = low
                        ssrc = AUDIO_SSRC
                    else:
                        session.video_port = low
                        ssrc = VIDEO_SSRC

                    if by_tcp:
                        # Каналы: плеер обычно называет их сам. Если не назвал
                        # -- раздаём по порядку: 0-1 первой дорожке, 2-3 второй.
                        asked = re.search(r"interleaved=(\d+)-(\d+)", transport)
                        if asked:
                            channels = (int(asked.group(1)), int(asked.group(2)))
                        else:
                            base = 2 * len(session.by_channel) // 2
                            channels = (base, base + 1)
                        session.open_relay_tcp(kind, channels, self.send_frame)
                    elif TWEAKS.get(session.variant, {}).get("relay"):
                        # Порт выдаёт система, и плееру называется именно он.
                        ours = session.open_relay(kind, client_ip, low)
                    else:
                        ours = AUDIO_FROM if kind == "audio" else VIDEO_FROM

                    # В RTP-Info потом называется тот самый адрес, который
                    # плеер прислал в SETUP -- так делают чужие серверы.
                    if not any(known == url for known, _ in session.tracks):
                        session.tracks.append((url, kind))

                    # В ответе возвращаются и порты плеера, и наши -- так
                    # требует протокол, и по нашим плеер будет сверять
                    # приходящие пакеты.
                    if by_tcp:
                        # При передаче по TCP портов нет вовсе -- только каналы.
                        self.reply(sequence, extra=[
                            "Session: 12345678;timeout=60",
                            "Transport: %s;unicast;interleaved=%d-%d;ssrc=%08X"
                            % (profile, channels[0], channels[1], ssrc)])
                    else:
                        self.reply(sequence, extra=[
                            "Session: 12345678;timeout=60",
                            "Transport: %s;unicast;client_port=%d-%d;server_port=%d-%d;ssrc=%08X"
                            % (profile, low, low + 1, ours, ours + 1, ssrc)])

                elif method == "PLAY":
                    # Второй заслон. Описание проверяется в DESCRIBE, но PLAY
                    # может прийти и без него -- адрес варианта к этому моменту
                    # уже известен из SETUP. А запускает ffmpeg именно PLAY.
                    if not session.pass_ok and not self.allowed(
                            session.variant, "", client_ip):
                        self.reply(sequence, status="401 Unauthorized")
                        break

                    # Плеер может попросить начать с определённого места --
                    # это и есть перемотка. Раньше она просто игнорировалась.
                    asked = self.header(request, "Range") or ""
                    found = re.search(r"npt=([0-9.]+)", asked)
                    if found:
                        wanted = float(found.group(1))
                        if wanted <= 0.05 and session.offset > 0.05:
                            # «С начала» для плеера -- это наше начало.
                            note("плеер просит с нуля, но в адресе задано "
                                 "начало %.1f с -- беру его" % session.offset)
                            session.position = session.offset
                        else:
                            session.position = wanted
                            note("просят начать с %.1f с" % session.position)

                    session.start(client_ip)

                    whole = LENGTHS.get(session.variant)
                    span = ("Range: npt=%.3f-%.3f" % (session.position, whole)
                            if whole else
                            "Range: npt=%.3f-" % session.position)
                    extra = ["Session: 12345678;timeout=60", span]
                    honest = TWEAKS.get(session.variant, {}).get("rtpinfo", True)
                    if session.tracks and honest:
                        # Числа берутся у счётчиков посредника: после PAUSE или
                        # перемотки они уже не нулевые, и назвать надо именно
                        # то, с чего продолжится поток.
                        pieces = []
                        for url, kind in session.tracks:
                            seq, stamp = session.expected.get(kind, (1, 0))
                            pieces.append("url=%s;seq=%d;rtptime=%d"
                                          % (url, seq, stamp))
                        extra.append("RTP-Info: " + ", ".join(pieces))
                    self.reply(sequence, extra=extra)

                elif method == "PAUSE":
                    # Телефон присылает PAUSE на каждое изменение громкости, а
                    # следом PLAY. Раньше сервер на PAUSE отвечал «хорошо» и
                    # продолжал лить, а на PLAY запускал ffmpeg заново С НАЧАЛА
                    # записи -- отсюда «когда делаю тише, всё ломается».
                    session.hold()
                    self.reply(sequence, extra=[
                        "Session: 12345678;timeout=60",
                        "Range: npt=%.3f-" % session.position])

                elif method == "TEARDOWN":
                    session.release()
                    self.reply(sequence, extra=["Session: 12345678;timeout=60"])
                    break

                else:
                    self.reply(sequence)
        except socket.timeout:
            # Молчит РАЗГОВОР. Пути потока могли при этом работать -- тогда
            # беда не в связи, а в нашем стороже, и это видно по числам.
            note("разговор молчал две минуты -- закрываю сессию")
            note("а на путях потока: %s" % session.tishina())
        except Exception as error:
            note("разговор оборвался: %s" % error)
        finally:
            session.release()
            note("--- отключился %s ---" % client_ip)

    def route(self, url):
        """Имя варианта и начальная секунда из адреса.

        Начальную секунду можно задать ТРЕМЯ способами -- все равноправны:

            rtsp://<сервер>/auto/at754      отдельным участком пути
            rtsp://<сервер>/auto?at=754     запросом
            rtsp://<сервер>/auto@754        через собачку

        Способов несколько не для красоты. Собачка в адресах отделяет имя
        пользователя от узла, и RealPlayer на телефоне на таком адресе завис
        на «выполняется подключение», до сервера не дойдя вовсе: он прочитал
        `auto@754` по-своему и стучался не туда. Разборщик 2007 года не
        переспоришь, поэтому основная форма -- `/auto/at754`, без единого
        особого знака. Собачка оставлена: CorePlayer её понимает, и по ней
        уже снято наблюдение.

        Зачем так. У RealPlayer на этом телефоне нет ни кнопок перемотки, ни
        шкалы: он всегда просит поток с нуля и ничем иным управлять не даёт.
        Но место начала выбирать может НАШЕ приложение -- оно и так рисует
        список серий и знает, где просмотр был прерван. Тогда перемотка
        выглядит так: в приложении двигается ползунок, приложение отдаёт
        системному плееру адрес с нужной секундой, и тот играет с неё. Ни
        патчить плеер, ни искать его исходники для этого не нужно.

        Отдельно от разбора заголовка Range в PLAY: там место просит сам
        плеер (так делает CorePlayer), а здесь -- мы.
        """
        path = re.sub(r"^rtsp://[^/]+", "", url, flags=re.IGNORECASE).strip("/")
        # Знаки вида %40 -- на случай, если плеер по дороге их закодировал.
        try:
            path = urllib.parse.unquote(path)
        except Exception:
            pass

        # Запрос (?at=754) отделяется первым: дальше разбирается только путь.
        path, _, query = path.partition("?")
        mark = ""
        found = re.search(r"at=([0-9.]+)", query)
        if found:
            mark = found.group(1)

        parts = [piece for piece in path.split("/") if piece]
        name = parts[0] if parts else ""

        # Общий вид: /jf/<запись>/at<секунда>. Запись -- опознаватель Jellyfin,
        # 32 знака. Это и есть рабочий адрес продукта: заранее прописанные
        # варианты остаются только для проб.
        if name.lower() == "jf" and len(parts) > 1:
            name = "jf-" + parts[1].lower()
            parts = parts[1:]
        # Участок пути вида at754 или at=754 -- в любом месте адреса.
        # Участок вида k<токен> -- пропуск от Jellyfin, тоже в любом месте.
        key = ""
        found = re.search(r"k=([0-9a-f]{16,64})", query, flags=re.IGNORECASE)
        if found:
            key = found.group(1)
        ekran = ""
        found = re.search(r"s=(\d{2,4}x\d{2,4})", query, flags=re.IGNORECASE)
        if found:
            ekran = found.group(1)
        for piece in parts[1:]:
            # Участок вида s320x240 -- экран телефона. Его называет само
            # приложение: оно знает свой экран, а человек про такое знать не
            # обязан. Без участка берётся умолчание сервера.
            spotted = re.match(r"^s=?(\d{2,4}x\d{2,4})$", piece,
                               flags=re.IGNORECASE)
            if spotted:
                ekran = spotted.group(1)
            spotted = re.match(r"^at=?([0-9.]+)$", piece, flags=re.IGNORECASE)
            if spotted:
                mark = spotted.group(1)
            spotted = re.match(r"^k=?([0-9a-f]{16,64})$", piece,
                               flags=re.IGNORECASE)
            if spotted:
                key = spotted.group(1)
        # Экран дописывается к имени варианта -- тем же видом, какой ждёт
        # name_of. Умолчательный экран в имя не пишется: иначе у одного и
        # того же телефона имя варианта менялось бы от настройки сервера.
        if ekran and name.startswith("jf-"):
            size = razbor_ekrana(ekran)
            if size != tuple(EKRAN):
                name = "%s-%dx%d" % (name, size[0], size[1])

        # И собачка, если она дошла до нас неискажённой.
        name, _, tail = name.partition("@")
        if tail:
            mark = tail

        start = 0.0
        if mark:
            try:
                start = max(0.0, float(mark))
            except ValueError:
                note("в адресе непонятная начальная секунда: %s" % mark)
        return self.name_of(name, url), start, key

    def host_of(self, url):
        """Хост с портом из адреса, как его назвал сам плеер."""
        spotted = re.match(r"^rtsp://([^/]+)", url, flags=re.IGNORECASE)
        if not spotted:
            return ""
        host = spotted.group(1)
        # Имя пользователя перед собачкой, если плеер его придумал, отбросить.
        return host.rpartition("@")[2]

    def variant_of(self, url):
        return self.route(url)[0]

    def allowed(self, variant, key, client_ip):
        """Пускать ли к перекодировке.

        Пробные варианты из файлов рядом -- свободно: это наша кухня, и
        наружу она не смотрит. Записи Jellyfin -- только по токену, либо
        из домашней сети, пока на телефоне стоит сборка без токена.
        """
        if not variant.startswith("jf-"):
            # В рабочем режиме других вариантов не бывает: файлов-образцов
            # на машине с Jellyfin нет. Значит всё, что не запись из
            # библиотеки, -- чужой стук, и отвечать на него нечего.
            #
            # Порт торчит наружу (иначе телефон не посмотрит из чужой сети),
            # и его находят сканеры: ходят путями видеокамер вроде
            # /cam/realmonitor и /h264/ch01/main/av_stream. Пока они упирались
            # в «описание не готово» -- то есть в случайность, а не в запрет.
            if PRODUKT:
                note("ОТКАЗ: %s просит не запись библиотеки (%s)"
                     % (client_ip, variant))
                return False
            return True
        if key_valid(key):
            return True
        if not STROGO and home_address(client_ip):
            note("без токена, но из домашней сети -- пускаю")
            return True
        note("ОТКАЗ: %s просит запись Jellyfin без годного токена" % client_ip)
        return False

    def name_of(self, name, url):
        """Есть ли такой вариант.

        Регистр схемы не важен: CorePlayer присылает «Rtsp://» с заглавной, и
        при строгом сравнении сервер не узнавал вариант и молча подсовывал
        умолчательный. Снаружи это выглядело как «играет, но картинка ужасная,
        длительности нет и через минуту всё сначала» -- то есть играл совсем
        не тот вариант, который просили.
        """
        if name in SDP:
            return name

        # Запись из библиотеки готовится по требованию: спрашиваем у неё
        # длительность и частоту кадров, остальное берём из шаблона.
        spotted = re.match(r"^jf-([0-9a-f]{32})(?:-(\d{2,4}x\d{2,4}))?$",
                           name, flags=re.IGNORECASE)
        if spotted:
            ready = prepare_item(spotted.group(1),
                                 razbor_ekrana(spotted.group(2)))
            if ready:
                return ready
            return name

        # Подставлять умолчательный вариант молча -- плохо: плеер играет не то,
        # что просили, и понять это со стороны телефона невозможно. Поэтому
        # имя возвращается как есть, а отказ выдаст DESCRIBE -- и в журнале
        # будет видно, чего именно просили.
        if name not in VARIANTS:
            note("просят неизвестный вариант: %s (из адреса %s)" % (name, url))
        return name if name in VARIANTS else DEFAULT

    def read_request(self):
        """Один запрос RTSP. По пути разбирает кадры данных от плеера.

        При передаче по TCP в одном соединении едут две разные вещи:
        текстовые запросы и двоичные кадры, начинающиеся со знака `$`
        (дальше номер канала -- один байт, и длина -- два). Если их не
        разбирать, отчёт плеера будет прочитан как мусорная строка запроса и
        разговор рассыплется.
        """
        lines = []
        while True:
            first = self.rfile.read(1)
            if not first:
                return None

            if first == b"$":
                head = self.rfile.read(3)
                if len(head) < 3:
                    return None
                channel = head[0]
                size = int.from_bytes(head[1:3], "big")
                payload = self.rfile.read(size) if size else b""
                relay = self.playing.by_channel.get(channel) if self.playing else None
                if relay is not None:
                    relay.from_player(payload)
                continue

            rest = self.rfile.readline() or b""
            line = (first + rest).decode("latin-1").strip()
            if not line:
                if lines:
                    break
                # Пустая строка до запроса -- остатки прошлого, пропускаем.
                continue
            lines.append(line)
        return lines

    def send_frame(self, channel, packet):
        """Отдать пакет плееру внутри соединения RTSP.

        Замок обязателен: сюда пишут два потока-посредника и сам разговор
        RTSP. Без него ответ на запрос может вклиниться в середину кадра, и
        тогда плеер потеряет счёт байтов навсегда.
        """
        if len(packet) > 0xFFFF:
            # Длина в кадре -- два байта, больше не уложить. Для RTP это не
            # ограничение: наши пакеты по тысяче байт.
            return
        frame = b"$" + bytes([channel & 0xFF]) + len(packet).to_bytes(2, "big")
        with self.writing:
            self.wfile.write(frame + packet)
            self.wfile.flush()

    def header(self, request, name):
        for line in request[1:]:
            if line.lower().startswith(name.lower() + ":"):
                return line.split(":", 1)[1].strip()
        return None

    def local_ip(self):
        probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            # Куда «подключиться», чтобы узнать СВОЙ адрес в сети.
            # Пакеты при этом не уходят: UDP-сокет только выбирает
            # исходящий сетевой путь. Адрес взят нейтральный и
            # перекрывается переменной PROBA_SHLYUZ -- в репозитории не
            # должно быть адресов чьей-то домашней сети.
            probe.connect((os.environ.get("PROBA_SHLYUZ") or "192.168.1.1", 1))
            return probe.getsockname()[0]
        finally:
            probe.close()

    def reply(self, sequence, extra=None, body=None, status="200 OK"):
        # Server, Date и Cache-Control ставят все чужие серверы. Сами по себе
        # они ничего не решают, но дешевле быть похожим на обычный сервер, чем
        # потом гадать, не из-за них ли клиент привередничает.
        lines = ["RTSP/1.0 " + status,
                 "CSeq: %s" % sequence,
                 "Server: jf-proba",
                 "Date: " + time.strftime("%a, %d %b %Y %H:%M:%S GMT",
                                          time.gmtime()),
                 "Cache-Control: no-cache"]
        lines += extra or []
        answer = ("\r\n".join(lines) + "\r\n\r\n").encode("latin-1")
        if body:
            answer += body
        with getattr(self, "writing", DUMMY_LOCK):
            self.wfile.write(answer)
            self.wfile.flush()


class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


if __name__ == "__main__":
    note("\n=== RTSP-сервер запущен, порт %d ===" % PORT)

    # Описания собираются в стороне, а сервер начинает слушать сразу. Иначе
    # живые варианты (обращение к Jellyfin) задерживают запуск на минуты, и
    # телефон в это время получает отказ на всё подряд.
    def prepare():
        if PRODUKT:
            # Описания записей Jellyfin собираются по первому запросу, а
            # пробным вариантам взяться неоткуда -- собирать нечего.
            note("рабочий режим: пробные варианты не собираются")
            return
        for name in sorted(VARIANTS):
            filename, streams = VARIANTS[name][0], VARIANTS[name][1]
            try:
                text = build_sdp(name, filename, streams)
            except Exception as error:
                note("вариант %s не собрался: %s" % (name, error))
                continue
            if text:
                SDP[name] = text
                note("готов вариант: rtsp://<адрес>/%s  (%s, дорожки %s)"
                     % (name, filename or "Jellyfin", streams))
        note("описания собраны, готовых вариантов: %d" % len(SDP))

    threading.Thread(target=prepare, daemon=True).start()
    Server(("0.0.0.0", PORT), Rtsp).serve_forever()
