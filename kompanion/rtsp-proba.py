def razgon_umeet():
    """Знает ли наш ffmpeg про разгон. Спрашивается один раз."""
    global RAZGON_MOZHNO
    if RAZGON_MOZHNO is None:
        try:
            out = subprocess.run([FFMPEG, "-hide_banner", "-h", "full"],
                                 stdout=subprocess.PIPE,
                                 stderr=subprocess.DEVNULL).stdout
            RAZGON_MOZHNO = b"readrate_initial_burst" in out
        except Exception as error:
            note("ffmpeg не опрошен про разгон: %s" % error)
            RAZGON_MOZHNO = False
        if not RAZGON_MOZHNO:
            note("ffmpeg не знает разгона -- отдаю ровно по времени")
    return RAZGON_MOZHNO


