# -*- coding: utf-8 -*-
"""
Пропуск RTP через себя с переписыванием номеров и меток времени.

Зачем это нужно.

Клиент внутри RealPlayer на Nokia -- это Helix DNA, то есть клиент стандарта
3GPP PSS. Он сводит дорожки между собой по числам из заголовка RTP-Info,
который сервер присылает в ответ на PLAY: `seq` (номер первого пакета) и
`rtptime` (метка времени первого пакета) для каждой дорожки.

У нас в этом заголовке стояло `seq=1;rtptime=0`, а ffmpeg начинает со
случайных значений и задать их не даёт (у упаковщика RTP есть -seq, но точки
отсчёта времени нет). Для ОДНОЙ дорожки эта неправда безобидна: сводить не с
чем, всё сдвигается одинаково, и поток играет. Для ДВУХ клиент считает по этим
числам их взаимное время, получает чепуху и не начинает воспроизведение
никогда -- ровно то, что наблюдалось на телефоне.

Задать точку отсчёта в ffmpeg нельзя, но её можно и не задавать: поток идёт
через этот посредник, первый пакет запоминается, и дальше номера идут с 1, а
метки времени -- с 0. Та же строка RTP-Info становится правдой.

Попутно переписывается метка времени в отчётах RTCP (SR): иначе клиент получил
бы из них другую точку отсчёта, чем из RTP-Info, и сведение сломалось бы снова,
но уже по-другому.

## Почему порты выдаёт система, а не я

Сначала порты были жёсткие (5004-5007) и сокеты создавались с флагом
«переиспользовать адрес». На Windows этот флаг для UDP разрешает ДВУМ сокетам
сесть на один порт, и датаграммы достаются только одному из них -- какому,
не определено. Если сокет прошлой сессии ещё не отпустил порт, новый садился
рядом и **не получал ничего**, молча.

На телефоне это выглядело так: видео пришло, звука нет, прогресс заполнен,
воспроизведение не началось. В журнале -- «пакетов пропущено: 898, 0, 0, 0».
Искать такое со стороны телефона почти невозможно.

Поэтому теперь: флага нет, порт на каждую сессию выдаёт система (пара соседних,
как требует RTP), и плееру называются те номера, которые реально заняты.
Занятый порт теперь даёт честную ошибку, а не тишину.

## Почему ошибка приёма больше не прерывает работу

Windows на UDP-сокете отдаёт ошибку 10054 («соединение сброшено») тому, кто
ОТПРАВЛЯЛ: если получатель закрыл порт, в ответ приходит ICMP «порт
недоступен», и его Windows выдаёт как ошибку следующего же `recvfrom` -- хотя
сокет цел и дальше работает нормально (проверено отдельной пробой: после пяти
таких ошибок сокет принял настоящий пакет).

Здесь на эту ошибку стояло `break`. То есть одна отбитая датаграмма от
телефона навсегда убивала поток-посредник: ffmpeg продолжал кодировать и
писать в сокет, который больше никто не читает, а на телефоне это выглядело
как вечная загрузка. Именно так и выходило при перемотке в CorePlayer: плеер
на перемотке закрывает прежнюю пару портов, пакет в полёте отбивается, и
дальше тишина. В журнале: счётчик пропущенных пакетов замирает, а ffmpeg
бодро пишет «speed=1.01x» ещё две минуты.

Теперь ошибки приёма переживаются, а их число видно в отчёте.

## Почему точка отсчёта у дорожек общая

Каждая дорожка считает время в своих единицах: у видео часы идут по 90000 в
секунду, у звука -- по 44100. Поначалу каждая продолжала счёт от своего
последнего отданного значения, и это казалось правильным: метки у дорожки
должны расти без разрыва.

Беда в том, что к моменту паузы дорожки отданы НЕ одинаково далеко. Один
ffmpeg кодирует обе, но отдаёт их разными выходами, и звук почти всегда
уходит вперёд видео: звуковой кадр дёшев, а картинку надо сжать. Полсекунды
разницы -- обычное дело.

После PLAY содержимое у обеих дорожек начинается с одного и того же места
записи, а метки времени продолжились с разных. Значит звук получил метку
позже, чем ему причиталось, -- и плеер честно отложил его на эту разницу.
Один раз это незаметно. Но телефон присылает PAUSE и PLAY на каждое
изменение громкости, и разницы складываются: за час просмотра звук отстал от
картинки на две-три секунды, причём на слух было слышно, как отставание
растёт. Вдобавок кусок звука, уже отданный до паузы, уходил второй раз --
это и есть жалоба на повторившуюся фразу.

Поэтому точка отсчёта теперь одна на все дорожки: берётся самое дальнее
место, до которого дошла любая из них, и переводится в единицы каждой.
Дорожки сдвигаются одинаково, и сводить их плееру больше нечего.

## Зачем читать отчёты плеера

Плеер по RTCP сам сообщает, сколько пакетов он потерял и какое дрожание
видит. Это единственный способ отличить «сеть теряет пакеты» от «телефон не
успевает декодировать»: снаружи и то и другое выглядит как рассыпающаяся на
квадраты картинка с постоянной подгрузкой. Раньше эти отчёты просто
пересылались ffmpeg непрочитанными.
"""

import os
import socket
import threading
import time


# Диапазон портов посредника.
#
# Дома годились любые, и порт выдавала система. Для работы из чужой сети так
# нельзя: телефон шлёт нам на эти порты, а дома между ним и нами свой роутер,
# и пробросить наугад взятый порт из шестидесяти тысяч невозможно. Поэтому
# диапазон узкий и постоянный -- его один раз пробрасывают целиком.
#
# Шестьдесят четыре порта -- это шестнадцать одновременных сеансов: на сеанс
# уходят четыре (данные и отчёты для каждой из двух дорожек). Для одного
# телефона с запасом.
# Какой перехлёст содержимого считать «продолжением», а не перемоткой.
#
# После паузы ffmpeg начинает с места, которое уже частично отдано: дорожки
# остановились не одинаково далеко. Этот перехлёст -- доли секунды, и его
# содержимое надо выбросить, иначе оно уйдёт плееру второй раз. А вот если
# человек сам отмотал назад на минуту, выбрасывать ничего нельзя -- он затем и
# отматывал. Различаем по величине: перехлёст мал, перемотка велика.
PEREHLYOST = 2.0

PORTS_FROM = int(os.environ.get("PROBA_PORTS_FROM") or "40000")
PORTS_TO = int(os.environ.get("PROBA_PORTS_TO") or "40063")


def bind_pair(tries=80):
    """Занять пару соседних портов: чётный под RTP, следующий под RTCP.

    Соседние нужны потому, что ffmpeg шлёт отчёты RTCP на «порт плюс один», и
    плеер ждёт того же. Чётный -- по тому же соглашению.
    """
    # Сначала свой диапазон, по порядку. Если он занят целиком -- берём, что
    # даст система: дома это по-прежнему работает, просто снаружи такой сеанс
    # будет недоступен. Отказать было бы хуже: дома важнее, чтобы играло.
    candidates = list(range(PORTS_FROM + PORTS_FROM % 2, PORTS_TO, 2))
    candidates += [0] * tries

    for port in candidates:
        rtp = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            rtp.bind(("0.0.0.0", port))
        except OSError:
            rtp.close()
            continue

        port = rtp.getsockname()[1]
        if port % 2:
            rtp.close()
            continue

        rtcp = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            rtcp.bind(("0.0.0.0", port + 1))
        except OSError:
            rtp.close()
            rtcp.close()
            continue

        return rtp, rtcp, port

    raise OSError("не нашлось свободной пары соседних портов")


class Track(object):
    """Счёт исходящих номеров и меток времени одной дорожки.

    Нумерацию ведёт посредник, а не ffmpeg: так в заголовке RTP-Info можно
    назвать правду, и так переживаются ПЕРЕЗАПУСКИ источника.

    Перезапуск бывает чаще, чем кажется. Телефон на каждое изменение громкости
    присылает PAUSE и следом PLAY; на перемотку -- PLAY с новым положением.
    Каждый раз ffmpeg запускается заново и начинает со своих случайных чисел.
    Если считать от ПЕРВОЙ точки отсчёта, после перезапуска номера уходят в
    чепуху, и воспроизведение рассыпается -- именно это и наблюдалось: «когда
    пытаюсь сделать тише или громче, всё ломается».

    Поэтому: номер пакета -- свой счётчик, он только растёт. Метка времени --
    продолжается с того места, где остановились, а внутри нового запуска
    считается от его собственного начала.

    Память общая для данных и отчётов RTCP: иначе они назвали бы клиенту
    разное время.
    """

    def __init__(self, rate=90000):
        # Частота часов RTP этой дорожки: 90000 у видео, 44100 у звука.
        # Нужна, чтобы переводить место записи в метки времени и обратно --
        # без этого дорожки нельзя привести к общему рубежу.
        self.rate = rate
        self.in_ts0 = None     # с какой метки начал нынешний запуск ffmpeg
        self.out_ts = 0        # сколько времени уже отдано плееру
        self.out_seq = 0       # сколько пакетов уже отдано
        self.carry = 0         # время, накопленное прошлыми запусками
        self.out_bytes = 0     # сколько полезной нагрузки отдано плееру
        self.skip_ticks = 0    # сколько содержимого выбросить в начале запуска
        self._lock = threading.Lock()

    def new_run(self, mesto=None):
        """Источник перезапускается с места `mesto` секунд записи.

        Задача -- чтобы у дорожки НЕ БЫЛО ни разрыва, ни повтора, и чтобы
        метка времени пакета равнялась месту записи в нём. Тогда плееру
        нечего домысливать, а домысливает он по-разному (см. шапку модуля).

        Два случая, и различаются они величиной перехлёста:

        * `mesto` позади того, что уже отдано, но ненамного -- это
          продолжение после паузы. Перехлёст выбрасываем (`skip_ticks`), а
          счёт продолжаем ровно с того значения, на котором встали: ни
          разрыва, ни повтора.
        * `mesto` впереди, или далеко позади -- это перемотка. Выбрасывать
          нечего, точка отсчёта становится самим местом.

        Без `mesto` -- продолжить от своего значения (так было раньше).
        """
        with self._lock:
            self.in_ts0 = None
            self.skip_ticks = 0
            if mesto is None:
                self.carry = self.out_ts
                return
            otdano = self.out_ts / float(self.rate)
            lishnee = otdano - mesto
            if self.out_seq > 0 and 0 <= lishnee <= PEREHLYOST:
                # Выбрасываем перехлёст и ещё один тик -- сам пограничный
                # пакет. Его содержимое тоже уже отдано, а метка времени у
                # него вышла бы ровно та же, что у последнего отданного: для
                # видео это два пакета с одной меткой, и плеер склеил бы их в
                # один испорченный кадр. Один кадр на каждую паузу.
                self.skip_ticks = int(round(lishnee * self.rate)) + 1
                self.carry = self.out_ts
            else:
                self.carry = int(round(mesto * self.rate))
                # Поднять и отданное: иначе следующий подсчёт возьмёт
                # устаревшее значение, если до него не придёт ни пакета.
                self.out_ts = self.carry

    def add_bytes(self, count):
        """Прибавить отданную полезную нагрузку.

        Нужно затем же, зачем свой счёт пакетов: в отчёте отправителя эти два
        числа должны быть НАШИ. Подробности -- у `_fix_rtcp`.
        """
        with self._lock:
            self.out_bytes += max(0, count)

    def totals(self):
        """Сколько пакетов и байтов отдано плееру за всё время."""
        with self._lock:
            return self.out_seq, self.out_bytes

    def emitted(self):
        """Докуда дошла дорожка, в секундах записи.

        По этому значению считается общий рубеж: берётся наибольшее из
        дорожек, чтобы ни одна не поехала назад.
        """
        with self._lock:
            return self.out_ts / float(self.rate)

    def expect(self):
        """Какие номер и метка будут у следующего пакета.

        Нужно для ответа на PLAY: в RTP-Info называются числа ПЕРВОГО пакета
        после этой команды.
        """
        with self._lock:
            return (self.out_seq + 1) & 0xFFFF, self.carry & 0xFFFFFFFF

    def take(self, timestamp):
        """Выдать номер и метку для очередного пакета от ffmpeg.

        `None` означает «этот пакет отдавать не надо»: его содержимое плеер
        уже получил до паузы.
        """
        with self._lock:
            if self.in_ts0 is None:
                self.in_ts0 = timestamp
            proshlo = (timestamp - self.in_ts0) & 0xFFFFFFFF
            if proshlo < self.skip_ticks:
                return None
            self.out_seq += 1
            self.out_ts = self.carry + (proshlo - self.skip_ticks)
            return self.out_seq & 0xFFFF, self.out_ts & 0xFFFFFFFF

    def since_run(self):
        """Сколько секунд записи отдано с последнего запуска источника.

        Нужно, чтобы честно сказать Jellyfin, до какого места досмотрели:
        считать по настенным часам нельзя -- соединение может висеть ещё
        долго после того, как плеер замолчал, и место уедет вперёд на эту
        разницу.
        """
        with self._lock:
            return max(0, self.out_ts - self.carry) / float(self.rate)

    def map_ts(self, timestamp):
        """Пересчитать метку времени, ничего не выдавая -- для отчётов RTCP."""
        with self._lock:
            if self.in_ts0 is None:
                return None
            proshlo = (timestamp - self.in_ts0) & 0xFFFFFFFF
            return (self.carry
                    + max(0, proshlo - self.skip_ticks)) & 0xFFFFFFFF


class Relay(object):
    """Один посредник: принимает от ffmpeg, переписывает, шлёт плееру.

    Сокет передаётся уже занятым -- его номер надо знать до ответа на SETUP,
    чтобы назвать плееру настоящий порт отправки.
    """

    def __init__(self, track, sock, client_ip, client_port, rtcp=False, note=None,
                 deliver=None):
        self.track = track
        self.sock = sock
        self.client = (client_ip, client_port)
        self.rtcp = rtcp
        self.note = note or (lambda text: None)
        # Если задано -- пакеты уходят не в UDP плееру, а сюда: это
        # передача внутри самого соединения RTSP (interleaved). Приём от
        # ffmpeg и переписывание при этом те же самые.
        self.deliver = deliver
        self.port = sock.getsockname()[1]
        self.passed = 0
        self.alive = True
        # Ошибки приёма, которые пережили. Раньше каждая из них была смертью.
        self.hiccups = 0
        # Пакеты, выброшенные как уже отданные (перехлёст после паузы).
        self.skipped = 0
        # Сколько раз отправка плееру не удалась.
        self.undelivered = 0
        # Сколько пакетов пришло ОТ плеера и откуда на самом деле.
        #
        # Это ключ к работе из чужой сети. Плееру за чужим роутером входящий
        # пакет на порт, с которого он сам ничего не слал, просто не дойдёт:
        # роутер не знает, кому его отдать. Но если плеер шлёт на свой же порт
        # данных хоть что-нибудь, дорога запоминается, и отвечать надо не на
        # порт из SETUP, а туда, откуда пришло.
        self.heard = 0
        self.heard_from = None
        # Когда от плеера приходило в последний раз.
        #
        # Нужно, чтобы отличить две совсем разные беды, которые в журнале
        # выглядели одинаково. Сессию закрывает молчание РАЗГОВОРА (TCP), а
        # поток идёт по другим путям (UDP). Если замолчало всё разом -- у
        # телефона пропала связь, и закрывать правильно. Если же разговор
        # замолчал, а пакеты от плеера шли -- значит сессию мы погасили сами
        # и зря. Без этого числа различить два случая нечем.
        self.last_heard = None
        # Пакеты с чужих адресов: признак либо чьей-то ошибки, либо попытки
        # увести поток. Считаем, чтобы это было видно, а не молчало.
        self.strangers = 0
        # Что плеер сообщил о потерях: (доля в процентах, всего потеряно,
        # дрожание в миллисекундах). Заполняется из отчётов RTCP.
        self.complaint = None
        self._complained_at = 0.0

        # Куда возвращать отчёты плеера. Узнаётся из первого пакета ffmpeg:
        # его порт больше не задаётся жёстко, и знать его заранее неоткуда.
        self.ffmpeg_port = None

        # До этого времени всё приходящее выбрасывается. Нужно при
        # перезапуске источника: в сокете остаются последние пакеты прошлого
        # ffmpeg, и если первый из них примут за начало нового запуска, точка
        # отсчёта времени возьмётся от старого -- и поток разъедется.
        self.ignore_until = 0.0

        self.sock.settimeout(1.0)
        self.thread = threading.Thread(target=self._run)
        self.thread.daemon = True
        self.thread.start()

    # --- переписывание ---

    def _fix_rtp(self, data):
        if len(data) < 12:
            return data

        timestamp = int.from_bytes(data[4:8], "big")
        vzyato = self.track.take(timestamp)
        if vzyato is None:
            return None
        new_seq, new_ts = vzyato

        out = bytearray(data)
        out[2] = (new_seq >> 8) & 0xFF
        out[3] = new_seq & 0xFF
        out[4:8] = new_ts.to_bytes(4, "big")
        # Заголовок RTP -- двенадцать байт, остальное полезная нагрузка.
        self.track.add_bytes(len(data) - 12)
        return bytes(out)

    def _fix_rtcp(self, data):
        # Переписывается только отчёт отправителя (SR, тип 200): метка времени
        # лежит в нём по смещению 16. Остальные виды отчётов идут как есть.
        if len(data) < 28 or data[1] != 200:
            return data

        mapped = self.track.map_ts(int.from_bytes(data[16:20], "big"))
        if mapped is None:
            return data

        out = bytearray(data)
        out[16:20] = mapped.to_bytes(4, "big")

        # Сколько пакетов и байтов отправлено -- тоже наши числа, а не
        # ffmpeg-овы.
        #
        # Нумерацию ведём мы, и она продолжается через перезапуски. А ffmpeg
        # на каждом запуске начинает счёт заново, и в отчёте отправителя
        # оказывалось «я отправил три тысячи пакетов» при пятидесяти тысячах
        # полученных. Плеер по этим числам сверяет свой учёт, и выходила
        # чепуха: он сообщал, что принял на целый круг номеров БОЛЬШЕ, чем
        # ждал (в журнале это видно как «всего -65002» при потерях 0.0%).
        #
        # Раз нумерация наша, то и счётчики к ней должны быть наши.
        packets, octets = self.track.totals()
        out[20:24] = (packets & 0xFFFFFFFF).to_bytes(4, "big")
        out[24:28] = (octets & 0xFFFFFFFF).to_bytes(4, "big")
        return bytes(out)

    # --- работа ---

    def _run(self):
        while self.alive:
            try:
                data, source = self.sock.recvfrom(65535)
            except socket.timeout:
                continue
            except OSError as error:
                # Сокет закрыли -- уходим. Иначе это ICMP-ответ от получателя
                # (10054 и родня): сокет цел, работа продолжается.
                if not self.alive or error.errno in (socket.EBADF, 10038, 10022):
                    break
                self.hiccups += 1
                continue

            if time.time() < self.ignore_until:
                # Остатки прошлого запуска -- выбросить.
                continue

            if source[0] in ("127.0.0.1", "::1"):
                # От ffmpeg -- переписать и отдать плееру.
                if self.ffmpeg_port is None:
                    self.ffmpeg_port = source[1]
                try:
                    fixed = self._fix_rtcp(data) if self.rtcp else self._fix_rtp(data)
                except Exception as error:
                    self.note("посредник: пакет не разобран (%s)" % error)
                    fixed = data
                if fixed is None:
                    # Содержимое уже отдано до паузы -- отдавать второй раз
                    # нельзя, человек слышит это как повтор фразы.
                    self.skipped += 1
                    continue
                try:
                    if self.deliver is not None:
                        self.deliver(fixed)
                    else:
                        self.sock.sendto(fixed, self.client)
                    self.passed += 1
                except OSError:
                    self.undelivered += 1
            else:
                # От плеера -- сначала прочитать жалобы, потом вернуть ffmpeg.
                self.heard += 1
                self.last_heard = time.time()
                if self.heard_from != source:
                    self.heard_from = source
                    self.note("посредник %d: плеер шлёт с %s:%d (ждали %s:%d)"
                              % (self.port, source[0], source[1],
                                 self.client[0], self.client[1]))
                if source != self.client:
                    # Симметричный ответ, но только по ПОРТУ и только для
                    # того же адреса.
                    #
                    # Менять порт надо: за чужим роутером наружу выходит не
                    # тот порт, который плеер назвал о себе сам. Менять адрес
                    # нельзя ни в коем случае: кто угодно, зная наш порт, мог
                    # бы прислать один поддельный пакет и увести поток на
                    # чужую машину. Для неё это был бы поток, которого она не
                    # просила, а для нас -- участие в нападении. Адрес берём
                    # из разговора RTSP: там он проверен самим соединением.
                    if source[0] == self.client[0]:
                        self.note("посредник %d: отвечаю на порт %d"
                                  % (self.port, source[1]))
                        self.client = source
                    else:
                        self.strangers += 1
                        if self.strangers in (1, 10, 100):
                            self.note("посредник %d: пакет с ЧУЖОГО адреса "
                                      "%s:%d -- не отвечаю (всего %d)"
                                      % (self.port, source[0], source[1],
                                         self.strangers))
                        continue
                if self.rtcp:
                    self._read_complaint(data)
                if self.ffmpeg_port is None:
                    continue
                try:
                    self.sock.sendto(data, ("127.0.0.1", self.ffmpeg_port))
                except OSError:
                    pass

    def from_player(self, data):
        """Пакет от плеера, пришедший по соединению RTSP, а не в сокет.

        При передаче по TCP другого пути у отчётов нет: всё идёт по тому же
        соединению. Содержимое разбирается так же и возвращается ffmpeg так же --
        ему всё равно, как отчёт добрался до нас.
        """
        self.last_heard = time.time()
        if self.rtcp:
            self._read_complaint(data)
        if self.ffmpeg_port is None:
            return
        try:
            self.sock.sendto(data, ("127.0.0.1", self.ffmpeg_port))
        except OSError:
            pass

    def _read_complaint(self, data):
        """Разобрать отчёт получателя (RR, тип 201) -- жалобу плеера.

        Отчёты RTCP приходят склеенными в один пакет, поэтому нужные блоки
        ищутся перебором: заголовок (4 байта), чей отчёт (4), дальше блоки по
        24 байта -- доля потерь (1), всего потеряно (3), старший номер (4),
        дрожание (4) и две метки.
        """
        offset = 0
        while offset + 4 <= len(data):
            kind = data[offset + 1]
            words = int.from_bytes(data[offset + 2:offset + 4], "big")
            size = (words + 1) * 4
            if size <= 0 or offset + size > len(data):
                break
            if kind == 201 and size >= 32:
                block = data[offset + 8:offset + 32]
                share = block[4] * 100.0 / 256.0
                # Со знаком: поле трёхбайтовое и знаковое, а плеер может
                # насчитать и отрицательное -- если принял больше, чем ждал
                # (повторы в сети). Без знака это выглядело как потеря
                # шестнадцати миллионов пакетов и пугало зря.
                lost = int.from_bytes(block[5:8], "big")
                if lost >= 0x800000:
                    lost -= 0x1000000
                jitter = int.from_bytes(block[12:16], "big")
                self.complaint = (share, lost, jitter)
                now = time.time()
                # Не чаще раза в десять секунд: отчёты идут каждые пять.
                if now - self._complained_at > 10.0:
                    self._complained_at = now
                    self.note("плеер сообщает: потеряно %.1f%% за интервал, "
                              "всего %d, дрожание %d единиц"
                              % (share, lost, jitter))
            offset += size

    def silent_for(self):
        """Сколько секунд от плеера на этот путь ничего не приходило.

        `None` -- не приходило ни разу за сессию.
        """
        if self.last_heard is None:
            return None
        return time.time() - self.last_heard

    def drop_leftovers(self, seconds=0.3):
        """Выбрасывать приходящее указанное время -- перед новым запуском."""
        self.ignore_until = time.time() + seconds

    def stop(self):
        self.alive = False
        try:
            self.sock.close()
        except OSError:
            pass
